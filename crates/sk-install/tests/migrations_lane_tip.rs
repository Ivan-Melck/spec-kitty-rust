//! `4.0.0rc5_install_lane_tip_recorder` acceptance tests.

use std::path::Path;
use std::process::Command;

use sk_install::migrations::lane_tip;

fn git(cwd: &Path, args: &[&str]) -> std::process::Output {
    Command::new("git")
        .args(args)
        .current_dir(cwd)
        .output()
        .expect("git")
}

fn repo() -> tempfile::TempDir {
    let directory = tempfile::tempdir().expect("temp");
    assert!(
        git(directory.path(), &["init", "-q", "-b", "main"])
            .status
            .success()
    );
    directory
}

#[test]
fn installs_both_hooks_with_the_exact_body_and_mode() {
    let directory = repo();
    let root = directory.path();
    assert!(lane_tip::detect(root).unwrap());
    let outcome = lane_tip::apply(root).unwrap();
    assert!(outcome.changed);
    assert_eq!(outcome.changes.len(), 2);
    assert!(!lane_tip::detect(root).unwrap());
    for name in ["post-commit", "post-rewrite"] {
        let path = root.join(".git/hooks").join(name);
        let text = std::fs::read_to_string(&path).unwrap();
        assert!(text.starts_with(
            "#!/bin/sh\n# Generated by spec-kitty (lane-tip recorder). Do not edit by hand.\n"
        ));
        assert!(text.contains("refs/heads/kitty/mission-*-lane-*"));
        assert!(text.contains("refs/spec-kitty/lane-tip/${b#refs/heads/}"));
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            assert_eq!(
                std::fs::metadata(&path).unwrap().permissions().mode() & 0o777,
                0o755
            );
        }
    }
    // A direct re-run rewrites the same bytes (the source installer is
    // idempotent by content, not by skipping the write); the migration runner
    // does not call it again because `detect` is false.
    let before = std::fs::read(root.join(".git/hooks/post-commit")).unwrap();
    let again = lane_tip::apply(root).unwrap();
    assert_eq!(again.changes.len(), 2);
    assert_eq!(
        std::fs::read(root.join(".git/hooks/post-commit")).unwrap(),
        before
    );
}

#[test]
fn a_foreign_hook_is_never_overwritten() {
    let directory = repo();
    let root = directory.path();
    let foreign = root.join(".git/hooks/post-commit");
    std::fs::create_dir_all(foreign.parent().unwrap()).unwrap();
    std::fs::write(&foreign, "#!/bin/sh\necho custom\n").unwrap();
    let outcome = lane_tip::apply(root).unwrap();
    assert!(outcome.changed);
    assert_eq!(outcome.changes.len(), 1);
    assert_eq!(
        std::fs::read_to_string(&foreign).unwrap(),
        "#!/bin/sh\necho custom\n"
    );
    assert!(root.join(".git/hooks/post-rewrite").is_file());
    assert!(
        outcome
            .warnings
            .iter()
            .any(|warning| warning.contains("not spec-kitty-managed"))
    );
}

#[test]
fn a_non_git_directory_is_not_applicable() {
    let directory = tempfile::tempdir().expect("temp");
    assert!(!lane_tip::detect(directory.path()).unwrap());
    assert!(lane_tip::can_apply(directory.path()).unwrap().is_some());
    assert!(!lane_tip::apply(directory.path()).unwrap().changed);
}

#[test]
fn a_dev_null_hooks_path_is_refused_and_nothing_is_written() {
    let directory = repo();
    let root = directory.path();
    assert!(
        git(root, &["config", "core.hooksPath", "/dev/null"])
            .status
            .success()
    );
    assert!(!lane_tip::detect(root).unwrap());
    let outcome = lane_tip::apply(root).unwrap();
    assert!(!outcome.changed);
    assert!(!root.join(".git/hooks/post-commit").exists());
}

#[test]
fn an_in_tree_hooks_path_is_refused() {
    let directory = repo();
    let root = directory.path();
    std::fs::create_dir_all(root.join(".husky")).unwrap();
    assert!(
        git(root, &["config", "core.hooksPath", ".husky"])
            .status
            .success()
    );
    assert!(!lane_tip::detect(root).unwrap());
    let outcome = lane_tip::apply(root).unwrap();
    assert!(!outcome.changed);
    assert!(!root.join(".husky/post-commit").exists());
}

#[test]
fn a_repository_private_hooks_path_outside_the_worktree_is_honoured() {
    let directory = repo();
    let root = directory.path();
    let outside = tempfile::tempdir().expect("hooks");
    assert!(
        git(
            root,
            &[
                "config",
                "core.hooksPath",
                outside.path().to_string_lossy().as_ref(),
            ],
        )
        .status
        .success()
    );
    assert!(lane_tip::detect(root).unwrap());
    let outcome = lane_tip::apply(root).unwrap();
    assert!(outcome.changed);
    assert!(outside.path().join("post-commit").is_file());
    assert!(!root.join(".git/hooks/post-commit").exists());
}
