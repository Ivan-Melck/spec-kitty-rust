/// The project's explicit `activated_skills` list, `None` when the key is absent.
pub fn explicit_activated_skills(
    project_root: &Path,
) -> Result<Option<BTreeSet<String>>, InstallError> {
    let ledger = sk_doctrine::load_activation_ledger(project_root)
        .map_err(|error| pack_skill_error(format!("cannot read the activation ledger: {error}")))?;
    Ok(ledger
        .allow_for(ArtifactKind::Skill)
        .map(|ids| ids.iter().cloned().collect()))
}

/// Whether a manifest records an installed pack skill (an unreadable manifest records none).
fn manifest_holds_pack_skills(project_root: &Path) -> Result<bool, InstallError> {
    let manifest = ManagedSkillManifest::load_strict(project_root)?;
    Ok(manifest.is_some_and(|manifest| {
        manifest
            .entries
            .iter()
            .any(|entry| entry.origin == ORIGIN_PACK)
    }))
}

/// Whether `project_root` shows evidence that pack skills matter to it.
///
/// True when a pack skill is installed or the explicit list is non-empty; total,
/// so an unreadable activation config counts as "matters" (a refusal, never a
/// silent retirement of installed skills).
pub fn pack_skills_matter(project_root: &Path, installed_pack_skills: bool) -> bool {
    if installed_pack_skills {
        return true;
    }
    match explicit_activated_skills(project_root) {
        Ok(Some(ids)) => !ids.is_empty(),
        Ok(None) => false,
        Err(_) => true,
    }
}

/// The resolved tier roots a pack-skill resolution reads.
struct PackRoots {
    built_in: PathBuf,
    org: Vec<PathBuf>,
    project: Option<PathBuf>,
}

fn resolve_roots(project_root: &Path) -> Result<PackRoots, InstallError> {
    let (built_in, org, project) = sk_doctrine::context_roots(project_root).map_err(|error| {
        pack_skill_error(format!("cannot resolve the charter pack roots: {error}"))
    })?;
    Ok(PackRoots {
        built_in,
        org,
        project,
    })
}

/// The merged built-in + org + project doctrine graph (the `requires` source).
fn merged_graph(project_root: &Path, roots: &PackRoots) -> Result<DrgGraph, InstallError> {
    let empty = || {
        DrgGraph::new("1.0", String::new(), String::new(), Vec::new(), Vec::new())
            .expect("an empty graph document is valid")
    };
    let built_in_dir = roots.built_in.clone();
    let built_in = if sk_doctrine::has_graph_files(&built_in_dir) {
        sk_doctrine::load_graph_or_dir(&built_in_dir)
            .map_err(|error| pack_skill_error(format!("cannot load the built-in DRG: {error}")))?
    } else {
        empty()
    };
    let mut fragments = Vec::new();
    for (position, root) in roots.org.iter().enumerate() {
        // An org pack ships its fragment at `drg/fragment.yaml`, which is not a
        // graph *directory* the generic loader recognises.
        if !root.join("drg").join("fragment.yaml").is_file() {
            continue;
        }
        let name = root
            .file_name()
            .map(|name| name.to_string_lossy().to_string())
            .unwrap_or_else(|| format!("org-{position}"));
        fragments.push(
            sk_doctrine::load_org_pack(&name, root, position).map_err(|error| {
                pack_skill_error(format!("cannot load org pack {name:?}: {error}"))
            })?,
        );
    }
    let project = match &roots.project {
        Some(root) if sk_doctrine::has_graph_files(root) => {
            Some(sk_doctrine::load_graph_or_dir(root).map_err(|error| {
                pack_skill_error(format!("cannot load the project DRG: {error}"))
            })?)
        }
        _ => None,
    };
    let report = sk_doctrine::merge_three_layers(&built_in, &fragments, project.as_ref())
        .map_err(|error| pack_skill_error(format!("cannot merge the DRG layers: {error}")))?;
    let _ = project_root;
    Ok(report.graph)
}

/// The org required `skills` floor as the **deny-netting** input.
///
/// This is the raw per-field floor read (`read_org_required_tokens`), the same
/// reader the deny composition (`org_required_stems`) is built on: a member the
/// strict per-field read refuses must not silently become "required" for the deny
/// arithmetic. It is deliberately NOT the in-force default — see
/// [`org_required_ids`].
fn org_required_floor(project_root: &Path) -> BTreeSet<String> {
    sk_doctrine::read_org_required_tokens(project_root, ArtifactKind::Skill, false)
        .unwrap_or_default()
        .into_iter()
        .collect()
}

/// The reference's *readability* leg for a project whose pack skills matter
/// (`require_org_skill_policy_readable`).
///
/// A configured pack whose `required_skills` is malformed must refuse rather than
/// read as "nothing required", which would retire installed skills.
fn require_readable_org_skill_policy(project_root: &Path) -> Result<(), InstallError> {
    let _ = sk_doctrine::read_org_required_tokens(project_root, ArtifactKind::Skill, true)
        .map_err(|error| {
            pack_skill_error(format!("cannot read the org required skills: {error}"))
        })?;
    Ok(())
}

/// The org required `skills` set as the **absent-key in-force default**.
///
/// `_absent_key_default` → `read_org_required_ids`: the lenient, coercing reader
/// that maps every list member through Python `str()` (`[1, ' x ', true, null]`
/// yields `1`, `x`, `True`, `None`) and skips a non-list value. The per-field floor
/// read answers `[]` for exactly that list, which would retire the skills the org
/// pack requires.
fn org_required_ids(project_root: &Path) -> Result<BTreeSet<String>, InstallError> {
    let required =
        sk_doctrine::read_org_required_ids(project_root, ArtifactKind::Skill).map_err(|error| {
            pack_skill_error(format!("cannot read the org required skills: {error}"))
        })?;
    Ok(required.into_iter().collect())
}

/// The project's deny tokens for skills, minus the org required floor.
fn effective_skill_deny(project_root: &Path) -> BTreeSet<String> {
    let Ok(ledger) = sk_doctrine::load_activation_ledger(project_root) else {
        return BTreeSet::new();
    };
    let deny = ledger.deny_for(ArtifactKind::Skill).to_vec();
    if deny.is_empty() {
        return BTreeSet::new();
    }
    let floor = org_required_floor(project_root);
    let Ok(index) = IdentityIndex::from_project(project_root) else {
        return deny.into_iter().collect();
    };
    sk_doctrine::effective_deny(
        ArtifactKind::Skill,
        deny,
        floor.into_iter().collect::<Vec<String>>(),
        &index,
    )
    .spellings()
}

fn render_active_pack_skills(
    project_root: &Path,
    shipped: &SkillCatalog,
) -> Result<Vec<(PreparedSkill, PythonString)>, InstallError> {
    let installed = match manifest_holds_pack_skills(project_root) {
        Ok(installed) => installed,
        Err(error) => {
            return Err(pack_skill_error(format!(
                "cannot read .kittify/skills-manifest.json: {error}"
            )));
        }
    };
    if !project_may_have_pack_skills(project_root, installed) {
        return Ok(Vec::new());
    }
    let explicit = explicit_activated_skills(project_root)?;
    let in_force = establish_in_force(project_root, installed, explicit)?;
    if in_force.is_empty() {
        return Ok(Vec::new());
    }
    let roots = resolve_roots(project_root)?;
    let org_namespace = sk_doctrine::read_org_skill_namespace(project_root).map_err(|error| {
        pack_skill_error(format!("cannot read the org skill namespace: {error}"))
    })?;
    let project_namespace =
        sk_charter::load_project_config(project_root, &sk_charter::Limits::default())
            .map_err(|error| {
                pack_skill_error(format!("cannot read .kittify/config.yaml: {error}"))
            })?
            .project_skill_namespace;
    let project_skills_dir = roots
        .project
        .as_ref()
        .map(|root| root.join(PACK_SKILLS_DIRNAME));
    let repository = PackSkillRepository::load(
        &roots.built_in.join(PACK_SKILLS_DIRNAME),
        &roots
            .org
            .iter()
            .map(|root| root.join(PACK_SKILLS_DIRNAME))
            .collect::<Vec<_>>(),
        project_skills_dir.as_deref(),
        None,
    )
    .map_err(|error| pack_skill_error(error.to_string()))?;
    let ids = match &in_force.ids {
        Some(ids) => ids.clone(),
        None => repository.ids().into_iter().collect(),
    };
    let graph = merged_graph(project_root, &roots)?;
    let prepared = prepare_skill_activations(
        &repository,
        &ids,
        &graph,
        org_namespace.as_deref(),
        project_namespace.as_deref(),
    )?;
    refuse_unsafe_names(&prepared)?;
    refuse_builtin_collisions(&prepared, shipped)?;
    let mut rendered = Vec::new();
    for item in prepared {
        let text = render_pack_skill(&item)?;
        rendered.push((item, text));
    }
    Ok(rendered)
}

fn project_may_have_pack_skills(project_root: &Path, installed: bool) -> bool {
    if pack_skills_matter(project_root, installed) {
        return true;
    }
    if let Ok(roots) = resolve_roots(project_root) {
        if let Some(project) = &roots.project
            && project.join(PACK_SKILLS_DIRNAME).is_dir()
        {
            return true;
        }
        return !roots.org.is_empty();
    }
    false
}

fn establish_in_force(
    project_root: &Path,
    installed: bool,
    explicit: Option<BTreeSet<String>>,
) -> Result<InForceSkills, InstallError> {
    if let Some(ids) = &explicit
        && ids.is_empty()
    {
        return Ok(InForceSkills {
            ids: Some(ids.clone()),
        });
    }
    if installed || explicit.is_some() {
        // The org policy decides only when the project does not; a project that
        // states its list still needs a readable org policy for the deny floor.
        let strict = explicit.is_none();
        if strict {
            require_readable_org_skill_policy(project_root)?;
        }
    }
    let deny = effective_skill_deny(project_root);
    let ids = match explicit {
        Some(ids) => ids,
        None => org_required_ids(project_root)?,
    };
    Ok(InForceSkills {
        ids: Some(ids.into_iter().filter(|id| !deny.contains(id)).collect()),
    })
}

fn refuse_unsafe_names(prepared: &[PreparedSkill]) -> Result<(), InstallError> {
    for item in prepared {
        if !is_one_safe_segment(&item.rendered_name) {
            return Err(pack_skill_error(format!(
                "pack skill {:?} would render as an unsafe directory name; {:?} is not a single safe path segment",
                item.id, item.rendered_name
            )));
        }
    }
    Ok(())
}

fn is_one_safe_segment(value: &str) -> bool {
    !value.is_empty()
        && value != "."
        && value != ".."
        && !value.contains(['/', '\\', '\0'])
        && !value.starts_with('.')
}

fn refuse_builtin_collisions(
    prepared: &[PreparedSkill],
    shipped: &SkillCatalog,
) -> Result<(), InstallError> {
    if prepared.is_empty() {
        return Ok(());
    }
    let shipped_names: BTreeSet<String> = shipped.names().into_iter().collect();
    for item in prepared {
        if shipped_names.contains(&item.rendered_name) {
            return Err(pack_skill_error(format!(
                "pack skill {:?} renders as {:?}, which is the name of a built-in skill; change its id or the pack's skill namespace",
                item.id, item.rendered_name
            )));
        }
    }
    Ok(())
}

/// Refuse a staging root reached through a symlinked or non-directory ancestor.
fn require_unlinked_staging_ancestry(project_root: &Path) -> Result<(), InstallError> {
    let mut current = project_root.to_path_buf();
    for component in Path::new(PACK_SKILL_STAGING_REL).components() {
        let Component::Normal(name) = component else {
            continue;
        };
        current.push(name);
        match std::fs::symlink_metadata(&current) {
            Ok(metadata) if metadata.file_type().is_symlink() => {
                return Err(pack_skill_error(format!(
                    "pack-skill staging root is not inside the project: {} is a symlink",
                    current.display()
                )));
            }
            Ok(metadata) if !metadata.is_dir() => {
                return Err(pack_skill_error(format!(
                    "pack-skill staging root is not inside the project: {} is not a directory",
                    current.display()
                )));
            }
            Ok(_) => {}
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                return Ok(());
            }
            Err(source) => {
                return Err(InstallError::io("inspect", &current, source));
            }
        }
    }
    Ok(())
}

/// Materialize the rendered set under the project staging root.
fn stage(
    project_root: &Path,
    rendered: &[(PreparedSkill, PythonString)],
) -> Result<Option<SkillCatalog>, InstallError> {
    let root = project_root.join(PACK_SKILL_STAGING_REL);
    require_unlinked_staging_ancestry(project_root)?;
    match std::fs::symlink_metadata(&root) {
        Ok(metadata) if metadata.file_type().is_symlink() => {
            return Err(pack_skill_error(format!(
                "pack-skill staging root is not a regular directory: {}",
                root.display()
            )));
        }
        Ok(metadata) if !metadata.is_dir() => {
            return Err(pack_skill_error(format!(
                "pack-skill staging root is not a regular directory: {}",
                root.display()
            )));
        }
        Ok(_) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            if rendered.is_empty() {
                return Ok(None);
            }
        }
        Err(source) => return Err(InstallError::io("inspect", &root, source)),
    }
    if rendered.is_empty() {
        if root.is_dir()
            && std::fs::read_dir(&root).is_ok_and(|mut entries| entries.next().is_some())
        {
            std::fs::remove_dir_all(&root)
                .map_err(|error| InstallError::io("remove", &root, error))?;
        }
        return Ok(None);
    }
    let wanted: BTreeSet<&str> = rendered
        .iter()
        .map(|(item, _)| item.rendered_name.as_str())
        .collect();
    if root.is_dir() {
        let mut children: Vec<PathBuf> = std::fs::read_dir(&root)
            .map_err(|error| InstallError::io("read directory", &root, error))?
            .map(|entry| entry.map(|entry| entry.path()))
            .collect::<Result<Vec<_>, _>>()
            .map_err(|error| InstallError::io("read directory entry", &root, error))?;
        children.sort();
        for child in children {
            let keep = child
                .file_name()
                .and_then(|name| name.to_str())
                .is_some_and(|name| wanted.contains(name));
            if !keep {
                remove_node(&child)?;
            }
        }
    }
    for (item, text) in rendered {
        write_staged(&root.join(&item.rendered_name).join(SKILL_FILENAME), text)?;
    }
    Ok(Some(SkillCatalog::discover(&root)?))
}

fn remove_node(path: &Path) -> Result<(), InstallError> {
    let metadata = std::fs::symlink_metadata(path)
        .map_err(|error| InstallError::io("inspect", path, error))?;
    if metadata.is_dir() && !metadata.file_type().is_symlink() {
        std::fs::remove_dir_all(path).map_err(|error| InstallError::io("remove", path, error))
    } else {
        std::fs::remove_file(path).map_err(|error| InstallError::io("remove", path, error))
    }
}

/// Write *text* only when it differs, so a warm resolution is a no-op.
///
/// Source `catalog._write_staged` encodes BEFORE path guards and atomic_write,
/// unlike generic Path.write_text. An encode failure creates no skill file.
fn write_staged(path: &Path, text: &PythonString) -> Result<(), InstallError> {
    let bytes = sk_kernel::python_utf8::encode_python_string(text).map_err(|error| {
        InstallError::io("write", path, std::io::Error::other(error.to_string()))
    })?;
    let parent = path.parent().unwrap_or_else(|| Path::new("."));
    if std::fs::symlink_metadata(parent).is_ok_and(|metadata| metadata.file_type().is_symlink()) {
        return Err(pack_skill_error(format!(
            "pack-skill staging directory is a symlink: {}",
            parent.display()
        )));
    }
    match std::fs::symlink_metadata(path) {
        Ok(metadata) if metadata.file_type().is_symlink() || metadata.is_dir() => {
            return Err(pack_skill_error(format!(
                "pack-skill staging path is not a regular file: {}",
                path.display()
            )));
        }
        Ok(_) => {
            if std::fs::read(path).is_ok_and(|existing| existing == bytes) {
                return Ok(());
            }
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(source) => return Err(InstallError::io("inspect", path, source)),
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|error| InstallError::io("create directory", parent, error))?;
    }
    sk_kernel::atomic_write(path, &bytes)
        .map_err(|error| InstallError::io("write", path, std::io::Error::other(error)))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(path, std::fs::Permissions::from_mode(STAGED_FILE_MODE));
    }
    Ok(())
}

/// The process-wide read-only staging parent (created once, never inside the project).
fn read_only_parent() -> Result<&'static Path, InstallError> {
    static ROOT: OnceLock<PathBuf> = OnceLock::new();
    if let Some(root) = ROOT.get() {
        return Ok(root);
    }
    let base = std::env::temp_dir().join(format!("spec-kitty-pack-skills-{}", std::process::id()));
    std::fs::create_dir_all(&base)
        .map_err(|error| InstallError::io("create directory", &base, error))?;
    let _ = ROOT.set(base);
    Ok(ROOT.get().expect("read-only root initialized"))
}

/// A content-addressed key of the rendered set.
fn rendered_set_key(rendered: &[(PreparedSkill, PythonString)]) -> Result<String, InstallError> {
    let mut digest = Sha256::new();
    let mut ordered: Vec<&(PreparedSkill, PythonString)> = rendered.iter().collect();
    ordered.sort_by(|left, right| left.0.rendered_name.cmp(&right.0.rendered_name));
    for (item, text) in ordered {
        // Source encodes every rendered part while computing the readonly key,
        // before any build directory or file. Do not defer this to write_staged.
        sk_kernel::python_utf8::encode_python_string(text).map_err(|error| {
            InstallError::io(
                "encode readonly cache key",
                &item.source_path,
                std::io::Error::other(error.to_string()),
            )
        })?;
        digest.update((item.rendered_name.len() as u64).to_be_bytes());
        digest.update(item.rendered_name.as_bytes());
        // This remains the Native cache digest/layout, not Source BLAKE2b.
        // The Source encoding gate above must still precede staging effects.
        digest.update((text.codepoints().len() as u64).to_be_bytes());
        for code in text.codepoints() {
            digest.update(code.to_be_bytes());
        }
    }
    Ok(format!("{:x}", digest.finalize()))
}

/// Render into a content-addressed subdirectory of the process-wide temp root.
///
/// The subdirectory is keyed by the rendered set and reused untouched when it
/// already exists, so the project tree is never written in this mode.
fn stage_read_only(
    rendered: &[(PreparedSkill, PythonString)],
) -> Result<Option<SkillCatalog>, InstallError> {
    if rendered.is_empty() {
        return Ok(None);
    }
    let root = read_only_parent()?.join(rendered_set_key(rendered)?);
    if !root.is_dir() {
        let building = root.with_file_name(format!(
            "{}.building",
            root.file_name()
                .map(|name| name.to_string_lossy().to_string())
                .unwrap_or_default()
        ));
        if building.exists() {
            std::fs::remove_dir_all(&building)
                .map_err(|error| InstallError::io("remove", &building, error))?;
        }
        for (item, text) in rendered {
            write_staged(
                &building.join(&item.rendered_name).join(SKILL_FILENAME),
                text,
            )?;
        }
        std::fs::rename(&building, &root)
            .map_err(|error| InstallError::io("rename", &root, error))?;
    }
    Ok(Some(SkillCatalog::discover(&root)?))
}

/// Resolve the project pack-skill catalog and merge it into the shipped catalog.
///
/// `stage = true` stages under `.kittify/runtime/pack-skills/` (the install,
/// apply and migration paths); `stage = false` renders into an out-of-project
/// read-only root (detect, assessment, dry-run, verify).
pub fn resolve_project_skill_catalog(
    project_root: &Path,
    stage_gap: bool,
) -> Result<SkillCatalog, InstallError> {
    resolve_project_skill_catalog_with(project_root, None, stage_gap)
}

/// [`resolve_project_skill_catalog`] with an injected shipped catalog.
pub fn resolve_project_skill_catalog_with(
    project_root: &Path,
    builtin: Option<&SkillCatalog>,
    stage_gap: bool,
) -> Result<SkillCatalog, InstallError> {
    let shipped = match builtin {
        Some(catalog) => catalog.clone(),
        None => shipped_catalog(),
    };
    let rendered = render_active_pack_skills(project_root, &shipped)?;
    let staged = if stage_gap {
        stage(project_root, &rendered)?
    } else {
        stage_read_only(&rendered)?
    };
    let Some(staged) = staged else {
        return Ok(shipped);
    };
    let mut merged = shipped;
    for skill in staged.skills() {
        let name = skill.name.clone();
        let Some((item, _)) = rendered.iter().find(|(item, _)| item.rendered_name == name) else {
            continue;
        };
        let mut tagged = skill.clone();
        tagged.origin = ORIGIN_PACK.to_string();
        tagged.source_ref = portable_ref(&item.source_path, project_root);
        tagged.source_hash = item.source_hash.clone();
        merged.push_skill(tagged);
    }
    Ok(merged)
}

/// Project-relative POSIX path when the source is inside the project, else absolute.
fn portable_ref(source: &Path, project_root: &Path) -> String {
    let resolved_source = source
        .canonicalize()
        .unwrap_or_else(|_| source.to_path_buf());
    let resolved_root = project_root
        .canonicalize()
        .unwrap_or_else(|_| project_root.to_path_buf());
    match resolved_source.strip_prefix(&resolved_root) {
        Ok(relative) => relative.to_string_lossy().replace('\\', "/"),
        Err(_) => source.to_string_lossy().replace('\\', "/"),
    }
}

/// The shipped (built-in) catalog: the offering skills tree, or an empty one.
pub fn shipped_catalog() -> SkillCatalog {
    match crate::migrations::completion_legacy::assets::offering_skills_root() {
        Some(root) => match SkillCatalog::discover(&root) {
            Ok(catalog) => catalog,
            Err(InstallError::SkillsCatalogMissing { .. }) => SkillCatalog::empty(root),
            Err(_) => SkillCatalog::empty(root),
        },
        None => SkillCatalog::empty(PathBuf::new()),
    }
}

/// The pack-origin skills of `catalog`, tagged with their rendered metadata.
pub fn pack_skills(catalog: &SkillCatalog) -> Vec<&CanonicalSkill> {
    catalog
        .skills()
        .iter()
        .filter(|skill| skill.origin == ORIGIN_PACK)
        .collect()
}

/// Whether `name` is a shipped (built-in) skill name.
pub fn is_builtin_origin(skill: &CanonicalSkill) -> bool {
    skill.origin == ORIGIN_BUILTIN
}

/// The staging root a project resolution writes, for callers that report it.
pub fn staging_root(project_root: &Path) -> PathBuf {
    project_root.join(PACK_SKILL_STAGING_REL)
}

/// One skill file's digest, `sha256:<hex>`.
pub fn file_digest(bytes: &[u8]) -> String {
    format!("sha256:{:x}", Sha256::digest(bytes))
}

/// Build the staged catalog's skill files for one skill directory (test helper).
pub fn skill_files(root: &Path, name: &str) -> Vec<SkillFile> {
    let mut files = Vec::new();
    let directory = root.join(name);
    let skill_md = directory.join(SKILL_FILENAME);
    if let Ok(bytes) = std::fs::read(&skill_md) {
        files.push(SkillFile {
            relative: SKILL_FILENAME.to_string(),
            source: skill_md,
            content_hash: file_digest(&bytes),
        });
    }
    files
}
