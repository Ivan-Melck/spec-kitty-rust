//! Charter-pack skill resolution: the project pack-skill catalog.
//!
//! Source: `src/charter/offering/pack_skills/{models,validation,repository}.py`,
//! `src/charter/activation/skill_preparation.py`,
//! `src/specify_cli/skills/{catalog,pack_skill_renderer}.py`.
//!
//! A *pack skill* is a thin, parameterized entry point shared through a charter
//! pack (ADR `2026-09-27-1`, ArtifactKind `skill`, URN `skill:<id>`). This module
//! owns the whole resolution chain so the one canonical [`crate::skills::SkillCatalog`]
//! sees the complete inventory the installer may manage:
//!
//! 1. **load** `*.skill.yaml` across the built-in, org (declaration order) and
//!    project pack tiers with the Source's tier rules (reserved prefixes, no
//!    `scripts/`, no permission-widening frontmatter), sibling-org-pack id
//!    conflicts, `overrides`/`enhances` folding and last-layer-wins overlay;
//! 2. **establish** which skills are in force from configuration alone (the
//!    project's explicit `activated_skills`, or the org packs' `required_skills`
//!    when the key is absent), refusing rather than reading "nothing required"
//!    when the project shows that pack skills matter;
//! 3. **prepare** each in-force skill (tier namespace, rendered name, Agent
//!    Skills limits, prompt body, DRG `requires` set) and **render** it;
//! 4. **stage** the rendered set under `.kittify/runtime/pack-skills/` (the write
//!    mode the installer stages) or into an out-of-project, content-addressed
//!    read-only root, and merge it into the shipped catalog tagged
//!    `origin: pack` with the pack source reference and input hash.
//!
//! Every refusal is decided in memory before the staging directory is touched,
//! so a refused resolution leaves the project tree byte-identical. Pack skills
//! are project-root only: they never feed a user-global asset batch.
//!
//! # Exact text, one owner
//!
//! The record is the Doctrine-owned exact [`PackSkill`] (exact Python code
//! points), and this module never scalarises it: preparation, `source_hash` and
//! the rendered `SKILL.md` are built from the same exact model dump, and the
//! rendered text is an exact [`PythonString`]. The reference serves a record
//! whose *unconstrained* string fields carry a code unit Rust `String` cannot
//! hold and fails only when it physically encodes the file; here that same
//! failure happens in [`write_staged`], through the canonical
//! [`sk_kernel::python_utf8::encode_python_string`] (`UnicodeEncodeError`
//! message included), never at load time.

