/// One in-force skill, ready to render.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct PreparedSkill {
    /// The skill id.
    pub id: String,
    /// The tier it resolved from.
    pub tier: PackTier,
    /// The name it renders under.
    pub rendered_name: String,
    /// Prompt or wrapper form.
    pub form: SkillForm,
    /// The prompt body (prompt form).
    pub body: Option<String>,
    /// The expansion (wrapper form).
    pub expansion: Option<SkillExpansion>,
    /// The sorted DRG `requires` targets (URN strings).
    pub requires: Vec<String>,
    /// The `*.skill.yaml` source file.
    pub source_path: PathBuf,
    /// `sha256:` digest of every input the rendered `SKILL.md` depends on.
    pub source_hash: String,
    /// The effective record.
    pub skill: PackSkill,
}

/// Which skills are in force for a project (`None`: every available skill).
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub struct InForceSkills {
    /// The ids, or `None` for "all available".
    pub ids: Option<BTreeSet<String>>,
}

impl InForceSkills {
    /// Whether the set is established and empty.
    pub fn is_empty(&self) -> bool {
        self.ids.as_ref().is_some_and(BTreeSet::is_empty)
    }
}

fn name_for(
    skill_id: &str,
    tier: PackTier,
    org_namespace: Option<&str>,
    project_namespace: Option<&str>,
) -> Result<String, InstallError> {
    if tier == PackTier::BuiltIn {
        return Ok(skill_id.to_string());
    }
    let (namespace, remedy) = match tier {
        PackTier::Org => (
            org_namespace,
            "set `skill_namespace` in the org pack's org-charter.yaml",
        ),
        _ => (
            project_namespace,
            "set `charter_packs.project.skill_namespace` in .kittify/config.yaml",
        ),
    };
    let Some(namespace) = namespace.filter(|value| !value.trim().is_empty()) else {
        return Err(pack_skill_error(format!(
            "{}-tier skill {skill_id:?} has no skill namespace to render under; {remedy}",
            tier.as_token()
        )));
    };
    if let Some(violation) = skill_namespace_violation(namespace) {
        return Err(pack_skill_error(format!("{violation}; {remedy}")));
    }
    let name = rendered_name(skill_id, Some(namespace));
    if RESERVED_PREFIXES
        .iter()
        .any(|prefix| name.starts_with(prefix))
    {
        return Err(pack_skill_error(format!(
            "{}-tier skill {skill_id:?} renders as {name:?}, a prefix reserved for built-in skills {:?}",
            tier.as_token(),
            RESERVED_PREFIXES
        )));
    }
    Ok(name)
}

fn prepare_skill_activations(
    repository: &PackSkillRepository,
    ids: &BTreeSet<String>,
    graph: &DrgGraph,
    org_namespace: Option<&str>,
    project_namespace: Option<&str>,
) -> Result<Vec<PreparedSkill>, InstallError> {
    let mut prepared: Vec<PreparedSkill> = Vec::new();
    for skill_id in ids {
        let Some(skill) = repository.skill(skill_id) else {
            let reported = if repository.warnings().is_empty() {
                String::new()
            } else {
                format!(
                    " (the loader reported: {})",
                    repository.warnings().join("; ")
                )
            };
            return Err(pack_skill_error(format!(
                "activated skill {skill_id:?} is not available in any pack tier{reported}"
            )));
        };
        let Some(source_path) = repository.source_path(skill_id) else {
            return Err(pack_skill_error(format!(
                "activated skill {skill_id:?} has no source record"
            )));
        };
        let tier = repository
            .tier_of(skill_id)
            .ok_or_else(|| pack_skill_error(format!("activated skill {skill_id:?} has no tier")))?;
        let name = name_for(skill_id, tier, org_namespace, project_namespace)?;
        let exact_name = PythonString::from_scalars(&name);
        if let Some(violation) = skill_limit_violation(skill, &exact_name) {
            return Err(pack_skill_error(violation));
        }
        let body = if skill.form == SkillForm::Prompt {
            Some(repository.body_text(skill_id).unwrap_or_default())
        } else {
            None
        };
        let requires = requires_of(graph, skill_id);
        let source_hash = source_hash(skill, body.as_deref(), &requires, &name);
        prepared.push(PreparedSkill {
            id: skill_id.clone(),
            tier,
            rendered_name: name,
            form: skill.form,
            body,
            expansion: skill.expands_to.clone(),
            requires,
            source_path: source_path.to_path_buf(),
            source_hash,
            skill: skill.clone(),
        });
    }
    let mut owners: BTreeMap<&str, &str> = BTreeMap::new();
    for item in &prepared {
        if let Some(previous) = owners.insert(&item.rendered_name, &item.id)
            && previous != item.id
        {
            return Err(pack_skill_error(format!(
                "skills {previous:?} and {:?} both render as {:?}; give one a different id or namespace",
                item.id, item.rendered_name
            )));
        }
    }
    Ok(prepared)
}

fn requires_of(graph: &DrgGraph, skill_id: &str) -> Vec<String> {
    let urn = format!("skill:{skill_id}");
    let mut targets: BTreeSet<String> = BTreeSet::new();
    for edge in graph.edges_from(&urn, Some(Relation::Requires)) {
        targets.insert(edge.target().to_string());
    }
    targets.into_iter().collect()
}

/// `sha256:` digest of every input the rendered `SKILL.md` depends on.
///
/// The canonical JSON of `{record, rendered_name, requires}` (sorted keys, the
/// one Kernel Python-JSON encoder, `ensure_ascii=True` exactly like Python
/// `json.dumps`) plus `\0` plus the body bytes, exactly as the Source's
/// `_source_hash`. The record half is the Doctrine-owned exact dump, so a
/// surrogate-bearing field is escaped as `\udXXX` rather than dropped.
pub fn source_hash(
    skill: &PackSkill,
    body: Option<&str>,
    requires: &[String],
    rendered_name: &str,
) -> String {
    let canonical = source_hash_payload(skill, requires, rendered_name);
    let mut digest = Sha256::new();
    digest.update(canonical.as_bytes());
    digest.update([0u8]);
    digest.update(body.unwrap_or_default().as_bytes());
    format!("sha256:{:x}", digest.finalize())
}

/// The canonical JSON payload `source_hash` digests: the record, the sorted
/// DRG `requires` and the rendered name, sorted-key Python JSON.
pub fn source_hash_payload(skill: &PackSkill, requires: &[String], rendered_name: &str) -> String {
    use sk_kernel::python_json::PythonJsonValue;

    let mut fields: BTreeMap<&str, PythonJsonValue> = BTreeMap::new();
    fields.insert("record", skill.model_dump_json());
    fields.insert(
        "rendered_name",
        PythonJsonValue::String(PythonString::from_scalars(rendered_name)),
    );
    fields.insert(
        "requires",
        PythonJsonValue::Array(
            requires
                .iter()
                .map(|item| PythonJsonValue::scalar(item))
                .collect(),
        ),
    );
    PythonJsonValue::Object(
        fields
            .into_iter()
            .map(|(key, value)| (key.to_string(), value))
            .collect(),
    )
    .render(None)
}

/// Render one prepared pack skill into `SKILL.md` text.
///
/// The text is exact Python code points ([`PythonString`]), never a Rust
/// `String`: the reference composes the same text and only a later physical
/// encode can fail on it. A wrapper's `builtin:` target is validated here against
/// the canonical command set, so an unknown target is refused before anything is
/// staged.
pub fn render_pack_skill(prepared: &PreparedSkill) -> Result<PythonString, InstallError> {
    let mut sections: Vec<PythonString> = Vec::new();
    sections.push(frontmatter(prepared));
    sections.push(PythonString::from_scalars(GENERATED_NOTICE));
    let mut title = PythonString::from_scalars("# ");
    title.append(&prepared.skill.title);
    sections.push(title);
    let preamble = context_preamble(&prepared.requires);
    if !preamble.is_empty() {
        sections.push(preamble);
    }
    let parameters = parameters_section(prepared);
    if !parameters.is_empty() {
        sections.push(parameters);
    }
    sections.push(instructions(prepared)?);
    let mut body = PythonString::default();
    for (position, section) in sections
        .into_iter()
        .filter(|section| !section.is_empty())
        .enumerate()
    {
        if position > 0 {
            body.push_scalars("\n\n");
        }
        body.append(&section);
    }
    body.push_scalars("\n");
    Ok(body)
}

/// `json.dumps(value, ensure_ascii=False)` — a JSON string is a valid
/// double-quoted YAML scalar, and the reference keeps authored code points
/// unescaped.
fn quoted(value: &PythonString) -> PythonString {
    use sk_kernel::python_json::PythonJsonValue;
    PythonJsonValue::String(value.clone()).render_python(None, false)
}

fn frontmatter(prepared: &PreparedSkill) -> PythonString {
    let mut front = PythonString::from_scalars("---\nname: ");
    front.append(&quoted(&PythonString::from_scalars(
        &prepared.rendered_name,
    )));
    front.push_scalars("\ndescription: ");
    front.append(&quoted(&rendered_description(&prepared.skill)));
    front.push_scalars("\nuser-invocable: ");
    front.push_scalars(if prepared.skill.invocation.user_invocable {
        "true"
    } else {
        "false"
    });
    if !prepared.skill.invocation.model_invocable {
        front.push_scalars("\ndisable-model-invocation: true");
    }
    front.push_scalars("\n---");
    front
}

fn context_preamble(requires: &[String]) -> PythonString {
    let mut preamble = PythonString::default();
    if requires.is_empty() {
        return preamble;
    }
    preamble.push_scalars(
        "## Governing context\n\nBefore acting, load the doctrine this skill depends on:\n\n",
    );
    for (position, urn) in requires.iter().enumerate() {
        if position > 0 {
            preamble.push_scalars("\n");
        }
        preamble.push_scalars("- `spec-kitty charter context --include ");
        preamble.push_scalars(urn);
        preamble.push_scalars("`");
    }
    preamble
}

fn parameters_section(prepared: &PreparedSkill) -> PythonString {
    let mut section = PythonString::default();
    if prepared.skill.parameters.is_empty() {
        return section;
    }
    section.push_scalars("## Parameters\n\n");
    for (position, parameter) in prepared.skill.parameters.iter().enumerate() {
        if position > 0 {
            section.push_scalars("\n");
        }
        section.push_scalars("- `");
        section.append(&parameter.name);
        section.push_scalars(if parameter.required {
            "` (required"
        } else {
            "` (optional"
        });
        if let Some(default) = &parameter.default {
            section.push_scalars(", default `");
            section.append(default);
            section.push_scalars("`");
        }
        section.push_scalars(")");
        if !parameter.description.is_empty() {
            section.push_scalars(": ");
            section.append(&parameter.description);
        }
    }
    section
}

fn instructions(prepared: &PreparedSkill) -> Result<PythonString, InstallError> {
    let mut body = PythonString::from_scalars("## Instructions\n\n");
    if prepared.form == SkillForm::Prompt {
        let text = prepared
            .body
            .clone()
            .unwrap_or_default()
            .replace("\r\n", "\n")
            .replace('\r', "\n");
        let text = text.trim();
        if text.is_empty() {
            return Err(pack_skill_error(format!(
                "prompt-form skill {:?} has an empty body",
                prepared.id
            )));
        }
        body.push_scalars(text);
        return Ok(body);
    }
    let Some(expansion) = &prepared.expansion else {
        return Err(pack_skill_error(format!(
            "wrapper-form skill {:?} has no expansion",
            prepared.id
        )));
    };
    body.append(&wrapper_instruction(&prepared.id, expansion)?);
    Ok(body)
}

fn wrapper_instruction(
    skill_id: &str,
    expansion: &SkillExpansion,
) -> Result<PythonString, InstallError> {
    let mut instruction = PythonString::default();
    let target = expansion
        .target
        .to_scalar_string()
        .expect("an admitted expansion target is ASCII");
    if let Some(name) = target.strip_prefix(BUILTIN_TARGET_PREFIX) {
        let command = validated_command(skill_id, name)?;
        instruction.push_scalars("Invoke the `");
        instruction.push_scalars(&command_skill_name(&command));
        instruction.push_scalars("` command skill.");
        if !expansion.args.is_empty() {
            instruction.push_scalars(" Pass these arguments: `");
            instruction.append(&expansion.args);
            instruction.push_scalars("`.");
        }
        return Ok(instruction);
    }
    if let Some(argv) = target.strip_prefix(CLI_TARGET_PREFIX) {
        instruction.push_scalars("Run the CLI command:\n\n```bash\n");
        instruction.push_scalars(argv.trim());
        if !expansion.args.is_empty() {
            instruction.push_scalars(" ");
            instruction.append(&expansion.args);
        }
        instruction.push_scalars("\n```");
        return Ok(instruction);
    }
    Err(pack_skill_error(format!(
        "wrapper skill {skill_id:?} has an unsupported target {:?}",
        expansion.target.repr()
    )))
}

/// `spec-kitty-<command>` for a canonical command.
fn command_skill_name(command: &str) -> String {
    format!("spec-kitty-{command}")
}

/// The pre-#6475 dotted alias.
fn legacy_command_skill_name(command: &str) -> String {
    format!("spec-kitty.{command}")
}

fn validated_command(skill_id: &str, name: &str) -> Result<String, InstallError> {
    let target = name.trim();
    for command in crate::agent::CANONICAL_COMMANDS {
        if target == command_skill_name(command) || target == legacy_command_skill_name(command) {
            return Ok(command.to_string());
        }
    }
    let known = crate::agent::CANONICAL_COMMANDS
        .iter()
        .map(|command| command_skill_name(command))
        .collect::<Vec<_>>()
        .join(", ");
    Err(pack_skill_error(format!(
        "wrapper skill {skill_id:?} targets unknown built-in command {name:?}; known commands: {known}"
    )))
}

