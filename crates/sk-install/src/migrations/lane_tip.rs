//! `4_0_0rc5_install_lane_tip_recorder`: install the lane work-tip hooks.
//!
//! The recorder is the tiny, dependency-free POSIX `sh` script the lane
//! allocator normally installs. A project upgraded after a mission was created
//! never reaches that allocator, so this one-shot migration writes the same
//! script into the effective hooks directory (`git rev-parse --git-path hooks`,
//! honouring a repository-private `core.hooksPath` and a linked worktree's
//! common dir).
//!
//! It never overwrites a foreign hook: a slot is written only when it is empty
//! or already carries the recorder's own signature. A `core.hooksPath` set at
//! global/system/command scope, or pointing into the working tree, is not
//! written because its hooks would affect every repository the user has.

use std::path::{Path, PathBuf};

use crate::error::InstallError;
use crate::upgrade::MigrationOutcome;

use super::git;

/// Signature line every recorder hook carries.
pub const LANE_TIP_HOOK_SIGNATURE: &str = "# Generated by spec-kitty (lane-tip recorder).";

/// Hidden ref namespace the hook updates.
pub const LANE_TIP_REF_PREFIX: &str = "refs/spec-kitty/lane-tip/";

const MISSION_BRANCH_PREFIX: &str = "kitty/mission-";
const HOOK_NAMES: [&str; 2] = ["post-commit", "post-rewrite"];

fn hook_body() -> String {
    format!(
        "#!/bin/sh\n\
         {LANE_TIP_HOOK_SIGNATURE} Do not edit by hand.\n\
         b=$(git symbolic-ref -q HEAD) || exit 0\n\
         case \"$b\" in refs/heads/{MISSION_BRANCH_PREFIX}*-lane-*) ;; *) exit 0 ;; esac\n\
         id=${{b##*-lane-}}\n\
         case \"$id\" in ''|*[!a-z]*) exit 0 ;; esac\n\
         git update-ref \"{LANE_TIP_REF_PREFIX}${{b#refs/heads/}}\" HEAD >/dev/null 2>&1\n\
         exit 0\n"
    )
}

fn resolve_hooks_dir(project_root: &Path) -> Result<PathBuf, InstallError> {
    let output = git::success_stdout(project_root, &["rev-parse", "--git-path", "hooks"])?
        .ok_or_else(|| InstallError::UpgradeRefused {
            detail: "not a git repository".to_string(),
        })?;
    let path = PathBuf::from(output);
    if path.is_absolute() {
        Ok(path)
    } else {
        Ok(project_root.join(path))
    }
}

fn hooks_path_scope(project_root: &Path) -> Result<Option<String>, InstallError> {
    let output = git::run(
        project_root,
        &["config", "--show-scope", "--get", "core.hooksPath"],
    )?;
    match output.status.code() {
        Some(1) => Ok(None),
        Some(0) => {
            let stdout = String::from_utf8_lossy(&output.stdout);
            let (scope, value) = match stdout.split_once('\t') {
                Some((scope, value)) => (scope.trim(), value.trim()),
                None => (stdout.trim(), ""),
            };
            Ok((!value.is_empty()).then(|| scope.to_string()))
        }
        _ => Ok(Some("unknown".to_string())),
    }
}

fn resolved(path: &Path) -> PathBuf {
    std::fs::canonicalize(path).unwrap_or_else(|_| path.to_path_buf())
}

fn working_tree_roots(project_root: &Path) -> Result<Vec<PathBuf>, InstallError> {
    let top_level = git::success_stdout(project_root, &["rev-parse", "--show-toplevel"])?
        .ok_or_else(|| InstallError::UpgradeRefused {
            detail: "not a git repository".to_string(),
        })?;
    let mut common = PathBuf::from(
        git::success_stdout(project_root, &["rev-parse", "--git-common-dir"])?.ok_or_else(
            || InstallError::UpgradeRefused {
                detail: "git common dir is unavailable".to_string(),
            },
        )?,
    );
    if !common.is_absolute() {
        common = project_root.join(common);
    }
    let mut roots = vec![resolved(Path::new(&top_level))];
    roots.push(resolved(common.parent().unwrap_or(common.as_path())));
    Ok(roots)
}

fn installable_hooks_dir(project_root: &Path) -> Result<Option<(PathBuf, String)>, InstallError> {
    let hooks_dir = resolve_hooks_dir(project_root)?;
    let Some(scope) = hooks_path_scope(project_root)? else {
        return Ok(Some((hooks_dir, String::new())));
    };
    if scope != "local" && scope != "worktree" {
        return Ok(Some((
            PathBuf::new(),
            format!(
                "core.hooksPath ({}) is set at {scope} scope, so its hooks run in every repository, not just this one",
                hooks_dir.display()
            ),
        )));
    }
    if !hooks_dir.is_dir() {
        return Ok(Some((
            PathBuf::new(),
            format!(
                "core.hooksPath resolves to {}, which is not a directory",
                hooks_dir.display()
            ),
        )));
    }
    let mut common_git_dir = PathBuf::from(
        git::success_stdout(project_root, &["rev-parse", "--git-common-dir"])?.ok_or_else(
            || InstallError::UpgradeRefused {
                detail: "git common dir is unavailable".to_string(),
            },
        )?,
    );
    if !common_git_dir.is_absolute() {
        common_git_dir = project_root.join(common_git_dir);
    }
    let in_git_dir = resolved(&hooks_dir).starts_with(resolved(&common_git_dir));
    if !in_git_dir
        && working_tree_roots(project_root)?
            .iter()
            .any(|root| resolved(&hooks_dir).starts_with(root))
    {
        return Ok(Some((
            PathBuf::new(),
            format!(
                "core.hooksPath resolves to {}, which is inside the working tree",
                hooks_dir.display()
            ),
        )));
    }
    Ok(Some((hooks_dir, String::new())))
}

fn is_lane_tip_hook(path: &Path) -> bool {
    match std::fs::read(path) {
        Ok(bytes) => String::from_utf8_lossy(&bytes).contains(LANE_TIP_HOOK_SIGNATURE),
        Err(_) => false,
    }
}

fn exists_or_symlink(path: &Path) -> bool {
    path.exists() || path.symlink_metadata().is_ok()
}

/// Hook slots that are genuinely empty, in canonical order.
pub fn pending_hook_names(project_root: &Path) -> Result<Vec<String>, InstallError> {
    let (hooks_dir, _reason) = match installable_hooks_dir(project_root) {
        Ok(Some(result)) => result,
        Ok(None) => return Ok(Vec::new()),
        Err(_) => return Ok(Vec::new()),
    };
    if hooks_dir.as_os_str().is_empty() {
        return Ok(Vec::new());
    }
    Ok(HOOK_NAMES
        .iter()
        .filter(|name| !exists_or_symlink(&hooks_dir.join(name)))
        .map(|name| (*name).to_string())
        .collect())
}

fn install_one(hooks_dir: &Path, name: &str) -> Result<Option<PathBuf>, InstallError> {
    let hook_path = hooks_dir.join(name);
    if exists_or_symlink(&hook_path) && !is_lane_tip_hook(&hook_path) {
        return Ok(None);
    }
    let mut temporary = tempfile::Builder::new()
        .prefix(&format!("{name}."))
        .tempfile_in(hooks_dir)
        .map_err(|source| InstallError::io("create hook temporary", hooks_dir, source))?;
    {
        use std::io::Write;
        temporary
            .write_all(hook_body().as_bytes())
            .map_err(|source| InstallError::io("write hook temporary", temporary.path(), source))?;
        temporary
            .flush()
            .map_err(|source| InstallError::io("flush hook temporary", temporary.path(), source))?;
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        temporary
            .as_file()
            .set_permissions(std::fs::Permissions::from_mode(0o755))
            .map_err(|source| InstallError::io("chmod hook temporary", temporary.path(), source))?;
    }
    temporary
        .persist(&hook_path)
        .map_err(|error| InstallError::io("install hook", &hook_path, error.error))?;
    Ok(Some(hook_path))
}

/// Detection: at least one genuinely empty hook slot in an installable directory.
pub fn detect(project_root: &Path) -> Result<bool, InstallError> {
    Ok(!pending_hook_names(project_root)?.is_empty())
}

/// Apply the recorder install.
pub fn apply(project_root: &Path) -> Result<MigrationOutcome, InstallError> {
    let (hooks_dir, reason) = match installable_hooks_dir(project_root) {
        Ok(Some(result)) => result,
        Ok(None) => return Ok(MigrationOutcome::skipped()),
        Err(error) => {
            return Ok(MigrationOutcome {
                changed: false,
                changes: Vec::new(),
                warnings: vec![format!("Skipping lane-tip recorder install: {error}.")],
                ..crate::upgrade::MigrationOutcome::default()
            });
        }
    };
    if hooks_dir.as_os_str().is_empty() {
        return Ok(MigrationOutcome {
            changed: false,
            changes: Vec::new(),
            warnings: vec![format!("Skipping lane-tip recorder install: {reason}.")],
            ..crate::upgrade::MigrationOutcome::default()
        });
    }
    std::fs::create_dir_all(&hooks_dir)
        .map_err(|source| InstallError::io("create hooks directory", &hooks_dir, source))?;
    let mut changes = Vec::new();
    let mut warnings = Vec::new();
    for name in HOOK_NAMES {
        match install_one(&hooks_dir, name)? {
            Some(path) => changes.push(format!(
                "installed lane-tip recorder hook: {}",
                path.file_name().unwrap_or_default().to_string_lossy()
            )),
            None => warnings.push(format!(
                "{} is not spec-kitty-managed; skipping lane-tip recorder install for this hook (its content is left untouched). Lane work-tip recording will only happen at spec-kitty's own lane touches until this hook is spec-kitty-managed.",
                hooks_dir.join(name).display()
            )),
        }
    }
    Ok(MigrationOutcome {
        changed: !changes.is_empty(),
        changes,
        warnings,
        ..crate::upgrade::MigrationOutcome::default()
    })
}

/// `can_apply` mirrors the source: only an existing Git project.
pub fn can_apply(project_root: &Path) -> Result<Option<String>, InstallError> {
    if !project_root.exists() {
        return Ok(Some(format!(
            "Project path does not exist: {}",
            project_root.display()
        )));
    }
    if git::success_stdout(project_root, &["rev-parse", "--git-dir"])?.is_none() {
        return Ok(Some(
            "lane-tip recorder already installed in every hook slot (or no git repository present)"
                .to_string(),
        ));
    }
    Ok(None)
}
