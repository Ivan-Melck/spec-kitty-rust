//! `.kittify/metadata.yaml`: project version metadata and the additive schema stamp.
//!
//! Two writers live here, matching upstream:
//!
//! - [`ProjectMetadata::save`] updates only the fields the model owns
//!   (`spec_kitty.version`, `initialized_at`, `last_upgraded_at`, an existing
//!   `schema_version`, and the `environment` triple) and leaves every other
//!   key, comment and quote byte-identical. A masked compare-before-write
//!   (`last_upgraded_at` neutralized) keeps a no-op save from churning the
//!   file.
//! - [`stamp_schema_metadata`] inserts `spec_kitty.schema_version` and
//!   `spec_kitty.schema_capabilities` only when those keys are entirely
//!   absent, preserving an operator-authored capability map and any author
//!   keys, and returning `false` without touching the file when nothing is
//!   missing.
//!
//! Both reuse [`crate::yaml_edit`], which proves each edit against a parsed
//! document before returning bytes. A malformed or non-mapping metadata file is
//! a typed refusal for `save` (upstream: `ValueError`) and a `false` no-op for
//! the init stamp (upstream: "the additive stamp only makes sense on
//! mappings").
//!
//! Deliberately not implemented: retiring a stale `migrations:` mirror block
//! once the migration ledger has been adopted. That requires the adoption
//! backfill's ledger state; [`crate::ledger`] exposes the ledger, and the
//! upgrade plan refuses the cutover until the native backfill exists rather
//! than deleting a mirror on an assumption.

use std::path::Path;

use serde_yaml_ng::{Mapping, Value};

use crate::error::InstallError;
use crate::plan::now_utc_iso;
use crate::yaml_edit::{InsertPosition, MappingEntry, Scalar, YamlEditor, parse_mapping};

/// The exact header written by a fresh metadata file.
pub const METADATA_HEADER: &str = "# Spec Kitty Project Metadata\n# Auto-generated by spec-kitty init/upgrade\n# DO NOT EDIT MANUALLY\n\n";

/// The schema version a current project stamps.
pub const CURRENT_SCHEMA_VERSION: i64 = 3;

/// The capability flags a current project stamps, in declaration order.
pub const CURRENT_SCHEMA_CAPABILITIES: [(&str, bool); 4] = [
    ("canonical_context", true),
    ("event_log_authority", true),
    ("ownership_manifest", true),
    ("thin_shims", true),
];

/// One legacy `migrations.applied` record, read for the one-time ledger backfill.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct LegacyMigrationRecord {
    /// The migration id recorded before the ledger cutover.
    pub id: String,
    /// The recorded result (`success`, `skipped`, `failed`).
    pub result: String,
}

/// Project metadata stored in `.kittify/metadata.yaml`.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ProjectMetadata {
    /// The CLI version that last wrote the project.
    pub version: String,
    /// When the project was initialized (ISO-8601, aware UTC).
    pub initialized_at: String,
    /// When the project was last upgraded, if ever.
    pub last_upgraded_at: Option<String>,
    /// The interpreter that initialized the project (environment provenance).
    pub python_version: String,
    /// The platform that initialized the project.
    pub platform: String,
    /// The platform release that initialized the project.
    pub platform_version: String,
    /// `spec_kitty.schema_version`, when present.
    pub schema_version: Option<i64>,
    /// Legacy applied-migration records (read-only; the ledger is authority).
    pub applied_migrations: Vec<LegacyMigrationRecord>,
}

impl ProjectMetadata {
    /// Build fresh metadata for a new project.
    pub fn for_new_project(
        version: impl Into<String>,
        initialized_at: impl Into<String>,
        python_version: impl Into<String>,
        platform: impl Into<String>,
        platform_version: impl Into<String>,
        schema_version: Option<i64>,
    ) -> Self {
        Self {
            version: version.into(),
            initialized_at: initialized_at.into(),
            last_upgraded_at: None,
            python_version: python_version.into(),
            platform: platform.into(),
            platform_version: platform_version.into(),
            schema_version,
            applied_migrations: Vec::new(),
        }
    }

    /// Read `.kittify/metadata.yaml`, tolerantly.
    ///
    /// An absent or unparseable file returns `None`, matching upstream: read
    /// paths must not fail because a metadata file is damaged.
    pub fn load(kittify_dir: &Path) -> Option<Self> {
        let path = kittify_dir.join("metadata.yaml");
        let text = std::fs::read_to_string(&path).ok()?;
        let mapping = parse_mapping(&path, &text).ok()?;
        let spec_kitty = mapping.get(Value::from("spec_kitty"));
        let spec_kitty = spec_kitty.and_then(Value::as_mapping);
        let get = |key: &str| -> Option<&Value> { spec_kitty?.get(Value::from(key)) };
        let string = |key: &str| get(key).and_then(Value::as_str).map(str::to_string);
        let environment = mapping
            .get(Value::from("environment"))
            .and_then(Value::as_mapping);
        let env = |key: &str| -> String {
            environment
                .and_then(|mapping| mapping.get(Value::from(key)))
                .and_then(Value::as_str)
                .unwrap_or_default()
                .to_string()
        };
        let schema_version = get("schema_version").and_then(Value::as_i64);
        let applied = mapping
            .get(Value::from("migrations"))
            .and_then(Value::as_mapping)
            .and_then(|migrations| migrations.get(Value::from("applied")))
            .and_then(Value::as_sequence)
            .map(|records| {
                records
                    .iter()
                    .filter_map(|record| {
                        let record = record.as_mapping()?;
                        Some(LegacyMigrationRecord {
                            id: record.get(Value::from("id"))?.as_str()?.to_string(),
                            result: record.get(Value::from("result"))?.as_str()?.to_string(),
                        })
                    })
                    .collect()
            })
            .unwrap_or_default();
        Some(Self {
            version: string("version").unwrap_or_else(|| "unknown".to_string()),
            initialized_at: string("initialized_at").unwrap_or_else(now_utc_iso),
            last_upgraded_at: string("last_upgraded_at"),
            python_version: env("python_version"),
            platform: env("platform"),
            platform_version: env("platform_version"),
            schema_version,
            applied_migrations: applied,
        })
    }

    /// The model-owned mapping this writer is authoritative for.
    pub fn model_owned_mapping(&self) -> Mapping {
        let mut spec_kitty = Mapping::new();
        if let Some(version) = self.schema_version {
            spec_kitty.insert(Value::from("schema_version"), Value::from(version));
        }
        spec_kitty.insert(Value::from("version"), Value::from(self.version.clone()));
        spec_kitty.insert(
            Value::from("initialized_at"),
            Value::from(self.initialized_at.clone()),
        );
        spec_kitty.insert(
            Value::from("last_upgraded_at"),
            match &self.last_upgraded_at {
                Some(value) => Value::from(value.clone()),
                None => Value::Null,
            },
        );
        let mut environment = Mapping::new();
        environment.insert(
            Value::from("python_version"),
            Value::from(self.python_version.clone()),
        );
        environment.insert(Value::from("platform"), Value::from(self.platform.clone()));
        environment.insert(
            Value::from("platform_version"),
            Value::from(self.platform_version.clone()),
        );
        let mut mapping = Mapping::new();
        mapping.insert(Value::from("spec_kitty"), Value::Mapping(spec_kitty));
        mapping.insert(Value::from("environment"), Value::Mapping(environment));
        mapping
    }

    /// Save the model-owned fields, preserving every other byte of the file.
    ///
    /// Returns `true` when the file was written, `false` when the masked
    /// content was already current.
    pub fn save(&self, kittify_dir: &Path) -> Result<bool, InstallError> {
        let path = kittify_dir.join("metadata.yaml");
        let existing = match std::fs::read(&path) {
            Ok(raw) => {
                Some(
                    String::from_utf8(raw).map_err(|error| InstallError::MetadataInvalid {
                        path: path.clone(),
                        detail: error.to_string(),
                    })?,
                )
            }
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => None,
            Err(source) => return Err(InstallError::io("read", &path, source)),
        };
        if let Some(text) = &existing {
            // Refuse a document this writer cannot merge into: parsing also
            // rejects a non-mapping root. An empty file is a valid empty base.
            parse_mapping(&path, text).map_err(|error| InstallError::MetadataInvalid {
                path: path.clone(),
                detail: error.to_string(),
            })?;
        }
        let mut text = match &existing {
            Some(text) if !text.trim_start_matches('\u{feff}').trim().is_empty() => text.clone(),
            _ => format!("{METADATA_HEADER}spec_kitty:\n"),
        };

        let spec_entries = vec![
            ("version".to_string(), Scalar::Str(self.version.clone())),
            (
                "initialized_at".to_string(),
                Scalar::Str(self.initialized_at.clone()),
            ),
            (
                "last_upgraded_at".to_string(),
                match &self.last_upgraded_at {
                    Some(value) => Scalar::Str(value.clone()),
                    None => Scalar::Null,
                },
            ),
        ];
        let mut outcome = YamlEditor::new(path.clone(), text)
            .upsert_scalars("spec_kitty", &spec_entries, InsertPosition::Top)
            .map_err(metadata_refusal(&path))?;
        text = outcome.text;
        if let Some(schema_version) = self.schema_version {
            outcome = YamlEditor::new(path.clone(), text)
                .upsert_scalars(
                    "spec_kitty",
                    &[("schema_version".to_string(), Scalar::Int(schema_version))],
                    InsertPosition::Top,
                )
                .map_err(metadata_refusal(&path))?;
            text = outcome.text;
        }
        let environment = vec![
            (
                "python_version".to_string(),
                Scalar::Str(self.python_version.clone()),
            ),
            ("platform".to_string(), Scalar::Str(self.platform.clone())),
            (
                "platform_version".to_string(),
                Scalar::Str(self.platform_version.clone()),
            ),
        ];
        let outcome = YamlEditor::new(path.clone(), text)
            .upsert_scalars("environment", &environment, InsertPosition::Bottom)
            .map_err(metadata_refusal(&path))?;
        let final_text = outcome.text;

        if let Some(existing) = &existing
            && mask_volatile(existing) == mask_volatile(&final_text)
        {
            return Ok(false);
        }
        sk_kernel::atomic_write(&path, final_text.as_bytes()).map_err(|error| {
            InstallError::io("write metadata", &path, std::io::Error::other(error))
        })?;
        Ok(true)
    }
}

fn metadata_refusal(path: &Path) -> impl Fn(InstallError) -> InstallError {
    let path = path.to_path_buf();
    move |error| InstallError::MetadataInvalid {
        path: path.clone(),
        detail: error.to_string(),
    }
}

/// Neutralize the volatile `last_upgraded_at` value for compare-before-write.
pub fn mask_volatile(text: &str) -> String {
    let mut masked = Vec::new();
    for line in text.lines() {
        let trimmed = line.trim_start();
        if trimmed.starts_with("last_upgraded_at:") {
            let indent = &line[..line.len() - trimmed.len()];
            masked.push(format!("{indent}last_upgraded_at: <masked>"));
        } else {
            masked.push(line.to_string());
        }
    }
    masked.join("\n")
}

/// Stamp `schema_version` / `schema_capabilities` additively.
///
/// Returns `true` when the file was created or modified. Existing values are
/// never overwritten, including an existing capability map.
pub fn stamp_schema_metadata(kittify_dir: &Path) -> Result<bool, InstallError> {
    let path = kittify_dir.join("metadata.yaml");
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|source| InstallError::io("create directory", parent, source))?;
    }
    let text = match std::fs::read(&path) {
        Ok(raw) => String::from_utf8(raw).map_err(|error| InstallError::MetadataInvalid {
            path: path.clone(),
            detail: error.to_string(),
        })?,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            format!("{METADATA_HEADER}spec_kitty:\n")
        }
        Err(source) => return Err(InstallError::io("read", &path, source)),
    };
    let mapping = match parse_mapping(&path, &text) {
        Ok(mapping) => mapping,
        Err(_) => {
            // Upstream refuses to mutate a non-mapping document and returns False.
            return Ok(false);
        }
    };
    let spec_kitty = mapping.get(Value::from("spec_kitty"));
    if let Some(value) = spec_kitty
        && !value.is_mapping()
        && !value.is_null()
    {
        // `spec_kitty:` holding a scalar is operator content; do not guess.
        return Ok(false);
    }
    let mut current = text.clone();
    let mut changed = false;
    let editor = YamlEditor::new(path.clone(), current.clone());
    let has_version = spec_kitty
        .and_then(Value::as_mapping)
        .is_some_and(|mapping| mapping.contains_key(Value::from("schema_version")));
    if !has_version {
        let outcome = editor
            .insert_scalars(
                "spec_kitty",
                &[(
                    "schema_version".to_string(),
                    Scalar::Int(CURRENT_SCHEMA_VERSION),
                )],
                InsertPosition::Top,
            )
            .map_err(metadata_refusal(&path))?;
        current = outcome.text;
        changed |= outcome.changed;
    }
    let has_capabilities = spec_kitty
        .and_then(Value::as_mapping)
        .is_some_and(|mapping| mapping.contains_key(Value::from("schema_capabilities")));
    if !has_capabilities {
        let editor = YamlEditor::new(path.clone(), current.clone());
        let outcome = editor
            .insert_mapping(
                "spec_kitty",
                &MappingEntry {
                    key: "schema_capabilities".to_string(),
                    children: CURRENT_SCHEMA_CAPABILITIES
                        .iter()
                        .map(|(capability, enabled)| {
                            ((*capability).to_string(), Scalar::Bool(*enabled))
                        })
                        .collect(),
                },
                InsertPosition::Bottom,
            )
            .map_err(metadata_refusal(&path))?;
        current = outcome.text;
        changed |= outcome.changed;
    }
    if !changed {
        return Ok(false);
    }
    sk_kernel::atomic_write(&path, current.as_bytes())
        .map_err(|error| InstallError::io("write metadata", &path, std::io::Error::other(error)))?;
    Ok(true)
}

/// The canonical capability map, in declaration order.
pub fn canonical_schema_capabilities() -> Mapping {
    let mut mapping = Mapping::new();
    for (capability, enabled) in CURRENT_SCHEMA_CAPABILITIES {
        mapping.insert(Value::from(capability), Value::from(enabled));
    }
    mapping
}

#[cfg(test)]
mod tests {
    use super::*;

    fn write(path: &Path, text: &str) {
        std::fs::create_dir_all(path.parent().unwrap()).expect("parent");
        std::fs::write(path, text).expect("write");
    }

    fn read(path: &Path) -> String {
        std::fs::read_to_string(path).expect("read")
    }

    #[test]
    fn creates_a_fresh_metadata_file_with_the_header_and_order() {
        let directory = tempfile::tempdir().expect("temp");
        let metadata = ProjectMetadata::for_new_project(
            "4.0.0rc8",
            "2026-11-02T19:52:04.299247+00:00",
            "3.11.15",
            "linux",
            "Linux-6.12",
            Some(CURRENT_SCHEMA_VERSION),
        );
        assert!(metadata.save(directory.path()).expect("save"));
        assert!(stamp_schema_metadata(directory.path()).expect("stamp"));
        let text = read(&directory.path().join("metadata.yaml"));
        assert!(text.starts_with(METADATA_HEADER));
        let schema = text.find("  schema_version:").unwrap();
        let version = text.find("\n  version:").unwrap();
        let initialized = text.find("\n  initialized_at:").unwrap();
        let upgraded = text.find("\n  last_upgraded_at:").unwrap();
        let capabilities = text.find("schema_capabilities:").unwrap();
        assert!(schema < version && version < initialized && initialized < upgraded);
        assert!(upgraded < capabilities);
        assert!(text.contains("  last_upgraded_at:\n"));
        assert!(text.contains("  schema_capabilities:\n    canonical_context: true\n"));
        assert!(text.contains("environment:\n  python_version: 3.11.15\n"));
    }

    #[test]
    fn second_stamp_is_a_no_op() {
        let directory = tempfile::tempdir().expect("temp");
        let path = directory.path().join("metadata.yaml");
        write(
            &path,
            &format!("{METADATA_HEADER}spec_kitty:\n  version: 1.0.0\n"),
        );
        assert!(stamp_schema_metadata(directory.path()).expect("stamp"));
        let first = read(&path);
        assert!(!stamp_schema_metadata(directory.path()).expect("stamp"));
        assert_eq!(read(&path), first);
    }

    #[test]
    fn preserves_operator_comments_and_capability_map() {
        let directory = tempfile::tempdir().expect("temp");
        let path = directory.path().join("metadata.yaml");
        let original = "# my header\nspec_kitty:\n  # operator note\n  version: 1.0.0\n  schema_capabilities:\n    custom: true  # keep\nproject_notes:\n  keep: me\n";
        write(&path, original);
        assert!(stamp_schema_metadata(directory.path()).expect("stamp"));
        let text = read(&path);
        assert!(text.contains("# my header"));
        assert!(text.contains("# operator note"));
        assert!(text.contains("custom: true  # keep"));
        assert!(text.contains("project_notes:\n  keep: me"));
        assert!(text.contains("schema_version: 3"));
        // The authored capability map is kept entirely: no canonical flags added.
        assert!(!text.contains("canonical_context"));
    }

    #[test]
    fn save_preserves_identity_comment_and_only_updates_owned_fields() {
        let directory = tempfile::tempdir().expect("temp");
        let path = directory.path().join("metadata.yaml");
        write(
            &path,
            "# header\nspec_kitty:\n  schema_version: 3\n  version: 1.0.0  # old\n  initialized_at: '2026-01-01T00:00:00+00:00'\n  last_upgraded_at:\n  schema_capabilities:\n    canonical_context: true\nproject:\n  uuid: keep-me  # identity\nenvironment:\n  python_version: 3.11.0\n  platform: linux\n  platform_version: old\n",
        );
        let mut metadata = ProjectMetadata::load(directory.path()).expect("load");
        metadata.version = "4.0.0rc8".to_string();
        metadata.last_upgraded_at = Some("2026-02-02T00:00:00+00:00".to_string());
        metadata.platform_version = "new".to_string();
        assert!(metadata.save(directory.path()).expect("save"));
        let text = read(&path);
        assert!(text.contains("uuid: keep-me  # identity"));
        assert!(text.contains("version: 4.0.0rc8  # old"));
        assert!(text.contains("last_upgraded_at: '2026-02-02T00:00:00+00:00'"));
        assert!(text.contains("platform_version: new"));
        assert!(text.contains("canonical_context: true"));
        // A second identical save is a masked no-op.
        assert!(!metadata.save(directory.path()).expect("save"));
    }

    #[test]
    fn save_refuses_a_non_mapping_file() {
        let directory = tempfile::tempdir().expect("temp");
        let path = directory.path().join("metadata.yaml");
        write(&path, "- not\n- a\n- mapping\n");
        let metadata = ProjectMetadata::for_new_project("1", "now", "", "", "", Some(3));
        let error = metadata.save(directory.path()).expect_err("refused");
        assert_eq!(error.code(), "metadata_invalid");
        assert_eq!(read(&path), "- not\n- a\n- mapping\n");
    }

    #[test]
    fn stamp_returns_false_for_non_mapping_documents() {
        let directory = tempfile::tempdir().expect("temp");
        let path = directory.path().join("metadata.yaml");
        write(&path, "- list\n");
        assert!(!stamp_schema_metadata(directory.path()).expect("no-op"));
        assert_eq!(read(&path), "- list\n");
    }
}
