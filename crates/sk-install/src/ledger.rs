/// The two-partition ledger for one project.
#[derive(Clone, Debug)]
pub struct MigrationLedger {
    project_root: PathBuf,
}

impl MigrationLedger {
    /// Open the ledger for `project_root`.
    pub fn new(project_root: impl Into<PathBuf>) -> Self {
        Self {
            project_root: project_root.into(),
        }
    }

    /// The tracked partition path.
    pub fn tracked_path(&self) -> PathBuf {
        self.project_root.join(TRACKED_LEDGER_REL)
    }

    /// The clone-local partition path.
    pub fn clone_local_path(&self) -> PathBuf {
        self.project_root.join(CLONE_LOCAL_LEDGER_REL)
    }

    /// The path authoritative for `clone_local`.
    pub fn path_for(&self, clone_local: bool) -> PathBuf {
        if clone_local {
            self.clone_local_path()
        } else {
            self.tracked_path()
        }
    }

    /// Read a partition, skipping malformed lines and normalizing legacy ids.
    pub fn records(&self, clone_local: bool) -> Result<Vec<LedgerRecord>, InstallError> {
        let path = self.path_for(clone_local);
        let raw = match sk_kernel::read_bounded(&path, 32 * 1024 * 1024) {
            Ok(raw) => raw,
            Err(sk_kernel::KernelError::Io { source, .. })
                if source.kind() == std::io::ErrorKind::NotFound =>
            {
                return Ok(Vec::new());
            }
            Err(error) => {
                return Err(InstallError::LedgerInvalid {
                    path,
                    detail: error.to_string(),
                });
            }
        };
        let text = String::from_utf8(raw).map_err(|error| InstallError::LedgerInvalid {
            path: path.clone(),
            detail: error.to_string(),
        })?;
        let mut records = Vec::new();
        for line in text.lines() {
            if line.trim().is_empty() {
                continue;
            }
            if let Some(record) = LedgerRecord::from_line(line) {
                records.push(record);
            }
        }
        Ok(normalize_ids(records))
    }

    /// The records authoritative for a spec's partition.
    pub fn records_for(&self, spec: &MigrationSpec) -> Result<Vec<LedgerRecord>, InstallError> {
        self.records(spec.clone_local)
    }

    /// Whether the normalized migration id has a `success` in its partition.
    /// Identity/content drift is audit-only and never reselects a settled id.
    pub fn is_settled(&self, spec: &MigrationSpec) -> Result<bool, InstallError> {
        Ok(self
            .records_for(spec)?
            .iter()
            .any(|record| record.id == spec.id && record.result == SETTLED_RESULT))
    }

    /// Append one record via a locked whole-file rewrite.
    pub fn append(&self, record: &LedgerRecord) -> Result<(), InstallError> {
        self.append_many(std::slice::from_ref(record))
    }

    /// Append many records, one locked rewrite per touched partition.
    pub fn append_many(&self, records: &[LedgerRecord]) -> Result<(), InstallError> {
        for clone_local in [false, true] {
            let batch: Vec<&LedgerRecord> = records
                .iter()
                .filter(|record| record.clone_local == clone_local)
                .collect();
            if batch.is_empty() {
                continue;
            }
            let path = self.path_for(clone_local);
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent)
                    .map_err(|source| InstallError::io("create directory", parent, source))?;
            }
            let _lock = acquire_ledger_lock(&path)?;
            let existing = read_raw_lines(&path)?;
            let mut lines = existing;
            lines.extend(batch.iter().map(|record| record.to_line()));
            let text = format!("{}\n", lines.join("\n"));
            match sk_kernel::atomic_write(&path, text.as_bytes()) {
                Ok(_) => {}
                Err(error) if error.mutation_may_have_committed() => {
                    let readback = std::fs::read_to_string(&path).unwrap_or_default();
                    if readback != text {
                        return Err(InstallError::IndeterminateCommit {
                            path,
                            detail: format!(
                                "ledger append may be visible but durability is unconfirmed: {error}"
                            ),
                        });
                    }
                }
                Err(error) => {
                    return Err(InstallError::io(
                        "append ledger record",
                        &path,
                        std::io::Error::other(error),
                    ));
                }
            }
        }
        Ok(())
    }

    /// The ids recorded in a partition (after legacy normalization).
    pub fn recorded_ids(&self, clone_local: bool) -> Result<BTreeSet<String>, InstallError> {
        Ok(self
            .records(clone_local)?
            .into_iter()
            .map(|record| record.id)
            .collect())
    }

    /// Seed every declared migration the project has already satisfied (init).
    ///
    /// Tracked migrations are seeded unconditionally; clone-local ones only when
    /// `clone_local_in_place` proves the effect exists on this checkout (fresh
    /// init outside git seeds none, so the first upgrade after `git init` applies
    /// them). Idempotent: a settled migration is never re-seeded.
    pub fn seed_for_init(
        &self,
        catalog: &MigrationCatalog,
        cli_version: &str,
        clone_local_in_place: impl Fn(&MigrationSpec) -> bool,
    ) -> Result<Vec<String>, InstallError> {
        let mut batches: BTreeMap<bool, Vec<LedgerRecord>> = BTreeMap::new();
        let mut seeded = Vec::new();
        for spec in catalog.specs() {
            if self.is_settled(spec)? {
                continue;
            }
            if spec.clone_local && !clone_local_in_place(spec) {
                continue;
            }
            batches
                .entry(spec.clone_local)
                .or_default()
                .push(LedgerRecord::for_spec(spec, SETTLED_RESULT, cli_version));
            seeded.push(spec.id.clone());
        }
        let records: Vec<LedgerRecord> = batches.into_values().flatten().collect();
        if !records.is_empty() {
            self.append_many(&records)?;
        }
        Ok(seeded)
    }
}

fn normalize_ids(records: Vec<LedgerRecord>) -> Vec<LedgerRecord> {
    let map: BTreeMap<&str, &str> = LEGACY_MIGRATION_ID_MAP.iter().copied().collect();
    let mut by_id: BTreeMap<String, LedgerRecord> = BTreeMap::new();
    for mut record in records {
        if let Some(canonical) = map.get(record.id.as_str()) {
            record.id = (*canonical).to_string();
        }
        by_id.insert(record.id.clone(), record);
    }
    by_id.into_values().collect()
}

fn read_raw_lines(path: &Path) -> Result<Vec<String>, InstallError> {
    match std::fs::read(path) {
        Ok(raw) => {
            let text = String::from_utf8(raw).map_err(|error| InstallError::LedgerInvalid {
                path: path.to_path_buf(),
                detail: error.to_string(),
            })?;
            Ok(text.lines().map(str::to_string).collect())
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(Vec::new()),
        Err(source) => Err(InstallError::io("read", path, source)),
    }
}

/// Whether a clone-local migration's effect is verifiably present on this checkout.
///
/// Upstream's predicate is `is_git_repo(root) and not migration.detect(root)`.
/// This native version recognizes the effects it can read without a Git
/// subprocess (the `info/exclude` entries, the merge-driver attributes+config
/// pair, and the hyphenated command-skill surface). Anything else answers
/// `false`, so the migration stays pending and the first upgrade (rather than a
/// false seed) owns it. Outside a git repository it always answers `false`.
pub fn clone_local_effect_in_place(project_root: &Path, spec: &MigrationSpec) -> bool {
    if !project_root.join(".git").exists() {
        return false;
    }
    match spec.id.as_str() {
        "0.13.1_exclude_worktrees" => git_exclude_contains(project_root, ".worktrees/"),
        "4.0.0rc7_exclude_spec_kitty" => git_exclude_contains(project_root, ".spec-kitty/"),
        "3.1.1_event_log_merge_driver" => {
            merge_drivers_in_place(project_root, "spec-kitty-event-log")
        }
        "3.2.6_decisions_event_log_merge_driver" => {
            merge_drivers_in_place(project_root, "spec-kitty-event-log")
        }
        // The historical gate-driver migration froze the *filled-side* driver
        // name for the issue matrix; the later repoint migration owns the
        // row-aware name, so a checkout holding only the repointed value does
        // not satisfy this migration (the pinned `detect()` says pending).
        "3.2.6_gate_artifact_merge_drivers" => {
            merge_driver_config_matches(
                project_root,
                "spec-kitty-acceptance-matrix",
                "Spec Kitty acceptance matrix filled-side merge",
                "spec-kitty merge-driver-acceptance-matrix %O %A %B",
            ) && merge_driver_config_matches(
                project_root,
                "spec-kitty-issue-matrix",
                "Spec Kitty issue matrix filled-side merge",
                "spec-kitty merge-driver-issue-matrix %O %A %B",
            ) && merge_driver_attributes_present(
                project_root,
                "spec-kitty-acceptance-matrix",
                &["kitty-specs/**/acceptance-matrix.json"],
            ) && merge_driver_attributes_present(
                project_root,
                "spec-kitty-issue-matrix",
                &["kitty-specs/**/issue-matrix.md"],
            )
        }
        "3.2.6_issue_matrix_driver_repoint" => {
            merge_drivers_in_place(project_root, "spec-kitty-issue-matrix")
        }
        "3.2.6_meta_traces_merge_drivers" => {
            merge_drivers_in_place(project_root, "spec-kitty-meta")
                && merge_drivers_in_place(project_root, "spec-kitty-traces")
        }
        "3.2.7_review_cycle_merge_driver" => {
            merge_drivers_in_place(project_root, "spec-kitty-review-cycle")
        }
        "4.0.0rc5_decision_index_merge_driver" => {
            merge_drivers_in_place(project_root, "spec-kitty-decision-index")
        }
        "4.0.0rc8_command_skill_hyphen_names" => !has_legacy_dotted_command_skills(project_root),
        "4.0.0rc8_retire_antigravity_workflows" => !has_legacy_antigravity_workflows(project_root),
        _ => false,
    }
}

fn git_exclude_contains(project_root: &Path, entry: &str) -> bool {
    let path = project_root.join(".git/info/exclude");
    std::fs::read_to_string(path)
        .map(|text| text.lines().any(|line| line.trim() == entry))
        .unwrap_or(false)
}

fn merge_driver_attributes_present(
    project_root: &Path,
    config_key: &str,
    patterns: &[&str],
) -> bool {
    std::fs::read_to_string(project_root.join(".gitattributes"))
        .map(|text| {
            patterns
                .iter()
                .all(|pattern| text.contains(&format!("{pattern} merge={config_key}")))
        })
        .unwrap_or(false)
}

fn merge_driver_config_matches(
    project_root: &Path,
    config_key: &str,
    name: &str,
    command: &str,
) -> bool {
    let Ok(text) = std::fs::read_to_string(project_root.join(".git/config")) else {
        return false;
    };
    text.contains(&format!("[merge \"{config_key}\"]"))
        && text.contains(&format!("name = {name}"))
        && text.contains(&format!("driver = {command}"))
}

fn merge_drivers_in_place(project_root: &Path, config_key: &str) -> bool {
    let Some(driver) = crate::attributes::MERGE_DRIVERS
        .iter()
        .find(|driver| driver.config_key == config_key)
    else {
        return false;
    };
    let attributes = project_root.join(".gitattributes");
    let attributes_ok = std::fs::read_to_string(&attributes)
        .map(|text| {
            driver
                .patterns
                .iter()
                .all(|pattern| text.contains(&format!("{pattern} merge={config_key}")))
        })
        .unwrap_or(false);
    if !attributes_ok {
        return false;
    }
    let config = project_root.join(".git/config");
    let Ok(text) = std::fs::read_to_string(config) else {
        return false;
    };
    text.contains(&format!("[merge \"{config_key}\"]"))
        && text.contains(&format!("name = {}", driver.name))
        && text.contains(&format!("driver = {}", driver.command))
}

/// Whether Antigravity's retired `.agent/workflows` command files are still
/// present for a project that has Antigravity configured.
///
/// Mirrors the pinned migration's `detect()`: an unconfigured project is
/// never processed (the old state cannot exist), a configured one is pending
/// while a `spec-kitty.*` workflow file, an unsafe workflows node, or an
/// unreadable configuration remains.
fn has_legacy_antigravity_workflows(project_root: &Path) -> bool {
    let configured = match crate::init::read_configured_agents(project_root) {
        Ok(agents) => agents.iter().any(|agent| agent == "antigravity"),
        // An unreadable configuration is a detect() warning upstream: pending.
        Err(_) => return true,
    };
    if !configured {
        return false;
    }
    let workflows = project_root.join(".agent/workflows");
    match std::fs::symlink_metadata(&workflows) {
        Ok(metadata) if metadata.file_type().is_symlink() => true,
        Ok(metadata) if !metadata.file_type().is_dir() => true,
        Ok(_) => match std::fs::read_dir(&workflows) {
            Ok(entries) => entries.flatten().any(|entry| {
                entry
                    .file_name()
                    .to_string_lossy()
                    .starts_with("spec-kitty.")
            }),
            Err(_) => true,
        },
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => false,
        Err(_) => true,
    }
}

fn has_legacy_dotted_command_skills(project_root: &Path) -> bool {
    let dotted = project_root.join(".agents/skills");
    if let Ok(entries) = std::fs::read_dir(dotted) {
        for entry in entries.flatten() {
            if entry
                .file_name()
                .to_string_lossy()
                .starts_with("spec-kitty.")
            {
                return true;
            }
        }
    }
    crate::skills::ManagedSkillManifest::load(project_root).is_some_and(|manifest| {
        manifest
            .entries
            .iter()
            .any(|entry| entry.installed_path.contains("/spec-kitty."))
    })
}

/// The lock-only sidecar for a ledger path, in the user state directory.
pub fn ledger_lock_path(ledger_path: &Path) -> Result<PathBuf, InstallError> {
    let unresolved = |error: sk_kernel::KernelError| InstallError::LedgerInvalid {
        path: ledger_path.to_path_buf(),
        detail: format!("could not resolve ledger lock authority: {error}"),
    };
    let state = sk_kernel::user_state_dir().map_err(unresolved)?;
    let resolved = sk_kernel::paths::resolve_path_non_strict(ledger_path).map_err(unresolved)?;
    let digest = Sha256::digest(resolved.to_string_lossy().as_bytes());
    let key: String = digest[..16]
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect();
    Ok(state
        .join("spec-kitty")
        .join("locks")
        .join("migration-ledger")
        .join(format!("{key}.lock")))
}

fn acquire_ledger_lock(path: &Path) -> Result<sk_kernel::FileLock, InstallError> {
    let lock_path = ledger_lock_path(path)?;
    if let Some(parent) = lock_path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|source| InstallError::io("create directory", parent, source))?;
    }
    sk_kernel::FileLock::acquire(&lock_path, LEDGER_LOCK_TIMEOUT).map_err(|error| match error {
        sk_kernel::KernelError::LockTimeout { .. } => InstallError::LedgerLockUnavailable {
            path: lock_path.clone(),
            waited_ms: LEDGER_LOCK_TIMEOUT.as_millis() as u64,
        },
        other => InstallError::io("lock", &lock_path, std::io::Error::other(other)),
    })
}

