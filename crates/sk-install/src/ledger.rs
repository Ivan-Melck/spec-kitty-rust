//! The two-partition migration ledger and the declared-migration catalog.
//!
//! The ledger is the single "already applied" authority (upstream
//! `upgrade/ledger.py`, ADR 2026-10-17-1). It is two append-only JSONL files:
//!
//! | Partition | Path | Routes |
//! | --- | --- | --- |
//! | tracked | `.kittify/migration-ledger.jsonl` | `clone_local_effect = false` |
//! | clone-local | `.kittify/migrations/clone-local.jsonl` | `clone_local_effect = true` |
//!
//! Every append is a **whole-file atomic rewrite under a per-ledger lock**, never
//! `O_APPEND`: a crash leaves a valid old-or-new file, never a torn record. The
//! lock lives in the user state directory, keyed by a digest of the resolved
//! ledger path, so it never shows up in `git status`. A wait that expires raises
//! [`InstallError::LedgerLockUnavailable`] with nothing appended.
//!
//! Lines are byte-compatible with the Python writer: keys in declaration order,
//! `": "`/`", "` separators, `clone_local` present only when true and
//! `superseded_by` only when set.
//!
//! The **catalog** is the declared migration set, embedded from the Python
//! reference snapshot (`src/migration_catalog.json`, generated by
//! `tools/generate_migration_catalog.py` at the pinned source revision). It
//! carries each migration's identity, target version, partition, git
//! requirement, supersession note and content hash. A native implementation is
//! a *separate* registry ([`crate::upgrade`]): the catalog never pretends a
//! migration has run, and an unimplemented selection is a typed refusal.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};
use std::time::Duration;

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::error::InstallError;
use crate::plan::now_utc_iso;

/// Tracked ledger path (project-relative).
pub const TRACKED_LEDGER_REL: &str = ".kittify/migration-ledger.jsonl";
/// Clone-local ledger path (project-relative).
pub const CLONE_LOCAL_LEDGER_REL: &str = ".kittify/migrations/clone-local.jsonl";
/// The only result that settles a migration.
pub const SETTLED_RESULT: &str = "success";
/// Non-settling outcomes the runner records.
pub const SKIPPED_RESULT: &str = "skipped";
/// Failure outcome.
pub const FAILED_RESULT: &str = "failed";
/// Bounded ledger-lock wait.
pub const LEDGER_LOCK_TIMEOUT: Duration = Duration::from_secs(30);

const CATALOG_JSON: &str = include_str!("migration_catalog.json");

// Source BaseMigration's inherited execution contract. Embedded catalogue rows
// carry explicit values; this default retains compatibility with older Native
// catalogue documents rather than creating a second id-based policy table.
fn default_runs_on_worktrees() -> bool {
    true
}

/// One declared migration.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct MigrationSpec {
    /// The migration id.
    pub id: String,
    /// The stable drift key (usually the id).
    pub identity: String,
    /// The defining module name at the reference snapshot (provenance).
    pub module: String,
    /// The version the migration targets.
    pub target_version: String,
    /// Whether the effect is clone-local (routes to the per-clone partition).
    pub clone_local: bool,
    /// Whether applying it requires a git repository.
    pub requires_git_repository: bool,
    /// Source's execution contract, independent of selection/ledger partition.
    /// Internal metadata: do not add a new key to existing serialized CLI rows.
    #[serde(default = "default_runs_on_worktrees", skip_serializing)]
    pub runs_on_worktrees: bool,
    /// A supersession note, empty when the migration is live.
    pub superseded_by: String,
    /// `sha256:<hex>` of the defining source bytes at the reference snapshot.
    pub content_hash: String,
}

/// The declared migration catalog, in canonical execution order.
#[derive(Clone, Debug)]
pub struct MigrationCatalog {
    specs: Vec<MigrationSpec>,
}

impl MigrationCatalog {
    /// The embedded catalog.
    pub fn embedded() -> Result<&'static Self, InstallError> {
        static CATALOG: std::sync::OnceLock<Result<MigrationCatalog, String>> =
            std::sync::OnceLock::new();
        match CATALOG.get_or_init(|| {
            MigrationCatalog::parse(CATALOG_JSON).map_err(|error| error.to_string())
        }) {
            Ok(catalog) => Ok(catalog),
            Err(detail) => Err(InstallError::MigrationCatalogInvalid {
                detail: detail.clone(),
            }),
        }
    }

    /// Parse and validate a catalog document (array of specs).
    pub fn parse(text: &str) -> Result<Self, InstallError> {
        let specs: Vec<MigrationSpec> =
            serde_json::from_str(text).map_err(|error| InstallError::MigrationCatalogInvalid {
                detail: error.to_string(),
            })?;
        if specs.is_empty() {
            return Err(InstallError::MigrationCatalogInvalid {
                detail: "catalog is empty".to_string(),
            });
        }
        let mut seen = BTreeSet::new();
        for spec in &specs {
            if spec.id.is_empty() || spec.identity.is_empty() || spec.target_version.is_empty() {
                return Err(InstallError::MigrationCatalogInvalid {
                    detail: "every spec needs id, identity and target_version".to_string(),
                });
            }
            if !seen.insert(spec.id.clone()) {
                return Err(InstallError::MigrationCatalogInvalid {
                    detail: format!("duplicate migration id {:?}", spec.id),
                });
            }
            crate::version::Version::parse(&spec.target_version).map_err(|error| {
                InstallError::MigrationCatalogInvalid {
                    detail: format!("{}: {error}", spec.id),
                }
            })?;
        }
        Ok(Self { specs })
    }

    /// Every spec in canonical order.
    pub fn specs(&self) -> &[MigrationSpec] {
        &self.specs
    }

    /// One spec by id.
    pub fn get(&self, id: &str) -> Option<&MigrationSpec> {
        self.specs.iter().find(|spec| spec.id == id)
    }

    /// How many specs are declared.
    pub fn len(&self) -> usize {
        self.specs.len()
    }

    /// Whether the catalog is empty (never true for a validated catalog).
    pub fn is_empty(&self) -> bool {
        self.specs.is_empty()
    }
}

/// One ledger record, in the upstream wire shape.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct LedgerRecord {
    /// The migration id (normalized from legacy aliases on read).
    pub id: String,
    /// When it was recorded (ISO-8601).
    pub applied_at: String,
    /// `success`, `skipped` or `failed`.
    pub result: String,
    /// The stable drift key.
    pub identity: String,
    /// The migration's content hash.
    pub content_hash: String,
    /// The CLI version that recorded it.
    pub cli_version: String,
    /// Serialized only when true.
    pub clone_local: bool,
    /// Serialized only when set.
    pub superseded_by: String,
}

impl LedgerRecord {
    /// Build the record for a declared migration and result.
    pub fn for_spec(spec: &MigrationSpec, result: &str, cli_version: &str) -> Self {
        Self {
            id: spec.id.clone(),
            applied_at: now_utc_iso(),
            result: result.to_string(),
            identity: spec.identity.clone(),
            content_hash: spec.content_hash.clone(),
            cli_version: cli_version.to_string(),
            clone_local: spec.clone_local,
            // Init/success records do not claim a supersession outcome. The
            // runner must explicitly stamp this only when it selects one.
            superseded_by: String::new(),
        }
    }

    /// Serialize one line, byte-compatible with `json.dumps(record.to_dict())`.
    pub fn to_line(&self) -> String {
        let mut fields: Vec<(&str, serde_json::Value)> = vec![
            ("id", serde_json::Value::String(self.id.clone())),
            (
                "applied_at",
                serde_json::Value::String(self.applied_at.clone()),
            ),
            ("result", serde_json::Value::String(self.result.clone())),
            ("identity", serde_json::Value::String(self.identity.clone())),
            (
                "content_hash",
                serde_json::Value::String(self.content_hash.clone()),
            ),
            (
                "cli_version",
                serde_json::Value::String(self.cli_version.clone()),
            ),
        ];
        if self.clone_local {
            fields.push(("clone_local", serde_json::Value::Bool(true)));
        }
        if !self.superseded_by.is_empty() {
            fields.push((
                "superseded_by",
                serde_json::Value::String(self.superseded_by.clone()),
            ));
        }
        let rendered: Vec<String> = fields
            .into_iter()
            .map(|(key, value)| {
                format!(
                    "{}: {}",
                    serde_json::to_string(key).expect("key"),
                    serde_json::to_string(&value).expect("value")
                )
            })
            .collect();
        format!("{{{}}}", rendered.join(", "))
    }

    fn from_line(line: &str) -> Option<Self> {
        let value: serde_json::Value = serde_json::from_str(line).ok()?;
        let text = |key: &str| value.get(key).and_then(serde_json::Value::as_str);
        let id = text("id")?.to_string();
        Some(Self {
            identity: text("identity").unwrap_or(&id).to_string(),
            id,
            applied_at: text("applied_at")?.to_string(),
            result: text("result")?.to_string(),
            content_hash: text("content_hash").unwrap_or_default().to_string(),
            cli_version: text("cli_version").unwrap_or("unknown").to_string(),
            clone_local: value
                .get("clone_local")
                .and_then(serde_json::Value::as_bool)
                .unwrap_or(false),
            superseded_by: text("superseded_by").unwrap_or_default().to_string(),
        })
    }
}

