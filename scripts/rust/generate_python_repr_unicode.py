#!/usr/bin/env python3
"""Generate the verified CPython ``str.isprintable()`` table used by ``python_repr``.

Development only: nothing in the Rust product imports this script, and the product
never runs Python. The table in ``crates/sk-invocation/src/python_unicode.rs`` is
derived from the pinned development interpreter after
``scripts/rust/verify_oracle.py`` proves that interpreter is the lock-exact one.

Usage (from the repository root, with the pinned oracle):

    .venv-rust-oracle/bin/python scripts/rust/generate_python_repr_unicode.py
    .venv-rust-oracle/bin/python scripts/rust/generate_python_repr_unicode.py --check

``--check`` fails (exit 1) when the committed table differs from a fresh
generation, so the table cannot drift silently. A missing or drifted interpreter
is a hard failure, never a skipped or empty comparison.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import tempfile
import unicodedata
from pathlib import Path

# The pinned reference interpreter (CPython 3.11.15); ``verify_oracle.py`` checks
# the runtime closure, this guards the exact bug-fix release the table came from.
EXPECTED_VERSION = (3, 11, 15)
EXPECTED_IMPLEMENTATION = "cpython"
EXPECTED_UNIDATA = "14.0.0"
LAST_CODE_POINT = 0x110000
OUTPUT = Path("crates/sk-invocation/src/python_unicode.rs")


def nonprintable_ranges() -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    for code in range(LAST_CODE_POINT):
        if chr(code).isprintable():
            continue
        if ranges and ranges[-1][1] + 1 == code:
            ranges[-1] = (ranges[-1][0], code)
        else:
            ranges.append((code, code))
    return ranges


def verify(root: Path) -> None:
    if sys.implementation.name != EXPECTED_IMPLEMENTATION:
        raise SystemExit(f"refusing to generate: requires {EXPECTED_IMPLEMENTATION}")
    if unicodedata.unidata_version != EXPECTED_UNIDATA:
        raise SystemExit(f"refusing to generate: requires Unicode {EXPECTED_UNIDATA}")
    version = tuple(sys.version_info[:3])
    if version != EXPECTED_VERSION:
        raise SystemExit(
            f"refusing to generate: interpreter {version} is not the pinned {EXPECTED_VERSION}"
        )
    verifier = root / "scripts/rust/verify_oracle.py"
    if not verifier.is_file():
        raise SystemExit(f"refusing to generate: missing oracle verifier {verifier}")
    with tempfile.TemporaryDirectory(prefix="sk-repr-oracle-") as cwd:
        result = subprocess.run(
            [sys.executable, str(verifier), "--root", str(root)],
            capture_output=True,
            text=True,
            check=False,
            cwd=cwd,
        )
    if result.returncode != 0:
        raise SystemExit(
            "refusing to generate: the development oracle is not lock-exact\n"
            f"{result.stdout}{result.stderr}"
        )


def render(ranges: list[tuple[int, int]], version: str) -> str:
    total = sum(end - start + 1 for start, end in ranges)
    rows = [f"    (0x{start:04x}, 0x{end:04x})," for start, end in ranges]
    joined = "\n".join(rows)
    return f'''//! Verified CPython `str.isprintable()` data for `python_repr`.
//!
//! Generated by `scripts/rust/generate_python_repr_unicode.py` from the pinned
//! development oracle (CPython 3.11.15) after `scripts/rust/verify_oracle.py`
//! proved the lock-exact interpreter. Do not edit by hand; regenerate with:
//!
//! ```text
//! .venv-rust-oracle/bin/python scripts/rust/generate_python_repr_unicode.py
//! ```
//!
//! `unicodedata.unidata_version` is {version}. The table lists every
//! non-printable code point of `U+0000..=U+10FFFF` as {len(ranges)} inclusive
//! ranges ({total:,} code points). ASCII space is printable and every surrogate
//! code unit is non-printable, exactly like the pinned interpreter. This is
//! `repr()` escaping data only: it makes no casefold, word-category or doctrine
//! claim, and the product never invokes Python at runtime.

use std::cmp::Ordering;

/// Number of inclusive non-printable ranges in [`NONPRINTABLE_RANGES`].
pub(crate) const NONPRINTABLE_RANGE_COUNT: usize = {len(ranges)};

/// Sorted, disjoint, inclusive ranges of non-printable code points.
pub(crate) const NONPRINTABLE_RANGES: &[(u32, u32)] = &[
{joined}
];

/// CPython `str.isprintable()` for one code point.
pub(crate) fn is_printable(code: u32) -> bool {{
    debug_assert_eq!(NONPRINTABLE_RANGES.len(), NONPRINTABLE_RANGE_COUNT);
    if code > 0x10ffff {{
        return false;
    }}
    !NONPRINTABLE_RANGES
        .binary_search_by(|&(start, end)| {{
            if end < code {{
                Ordering::Less
            }} else if start > code {{
                Ordering::Greater
            }} else {{
                Ordering::Equal
            }}
        }})
        .is_ok()
}}

#[cfg(test)]
mod tests {{
    use super::*;

    #[test]
    fn table_is_sorted_disjoint_and_counted() {{
        // The generator and the integration oracle test pin these facts.
        assert_eq!(NONPRINTABLE_RANGE_COUNT, {len(ranges)});
        assert_eq!(NONPRINTABLE_RANGES.len(), NONPRINTABLE_RANGE_COUNT);
        let mut total = 0u32;
        let mut previous_end = None;
        for &(start, end) in NONPRINTABLE_RANGES {{
            assert!(start <= end, "range {{start:#06x}}..{{end:#06x}} is ordered");
            assert!(end <= 0x10ffff, "range stays inside Unicode");
            if let Some(previous) = previous_end {{
                assert!(previous < start, "ranges are disjoint and sorted");
            }}
            total += end - start + 1;
            previous_end = Some(end);
        }}
        assert_eq!(total, {total:_}, "the table is never vacuous");
    }}

    #[test]
    fn pinned_printability_facts_match_cpython() {{
        assert!(is_printable(0x20), "ASCII space is printable");
        assert!(is_printable(0x21));
        assert!(is_printable(0x7e));
        for code in [0x00, 0x09, 0x0a, 0x0d, 0x1f, 0x7f, 0x80, 0x85, 0xa0, 0xad] {{
            assert!(!is_printable(code), "{{code:#06x}} is non-printable");
        }}
        for code in [0x0378, 0x200b, 0x2028, 0x2029, 0xd800, 0xdc00, 0xdfff] {{
            assert!(!is_printable(code), "{{code:#06x}} is non-printable");
        }}
        for code in [0xe000, 0xfeff, 0x1d173, 0xe0001, 0x10ffff] {{
            assert!(!is_printable(code), "{{code:#06x}} is non-printable");
        }}
        for code in [0xe9, 0x2603, 0x3b1, 0x10000, 0x1f600] {{
            assert!(is_printable(code), "{{code:#06x}} is printable");
        }}
        assert!(!is_printable(0x110000), "beyond Unicode is non-printable");
    }}
}}
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[2],
        help="repository root (default: two levels above this script)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed table instead of writing it",
    )
    args = parser.parse_args()
    root: Path = args.root.resolve()
    verify(root)
    ranges = nonprintable_ranges()
    text = render(ranges, unicodedata.unidata_version)
    target = root / OUTPUT
    if args.check:
        existing = target.read_text(encoding="utf-8")
        if existing != text:
            raise SystemExit(f"refusing: {OUTPUT} differs from a fresh verified generation")
        print(f"{OUTPUT}: up to date ({len(ranges)} ranges)")
        return 0
    target.write_text(text, encoding="utf-8")
    print(f"{OUTPUT}: wrote {len(ranges)} verified ranges")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
