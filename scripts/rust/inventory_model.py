def family_for(path: str) -> tuple[str, bool, str | None]:
    """Return ``(family, mutates, mutation_trigger)`` for a leaf path.

    Unknown paths are deliberately ``unresolved``: the completion checker then
    refuses to treat the inventory as complete.  New upstream commands must be
    classified, not dropped.
    """
    if path in _FAMILY_EXACT:
        family = _FAMILY_EXACT[path]
        return family, family != "read_only", None
    if path in READ_ONLY_PATHS:
        return "read_only", False, None
    if path in CONDITIONAL_MUTATION:
        return "conditional_repair", True, CONDITIONAL_MUTATION[path]
    if path.startswith("doctor/"):
        return "read_only", False, None
    if path.startswith("migrate/"):
        return "migration", True, None
    return "unresolved", False, None


