def _contract(
    *,
    family: str,
    writes: list[str],
    authority: list[str],
    source_refs: list[str],
    locks: list[str] | None = None,
    git_effects: list[str] | None = None,
    rollback: str = "none (append-only or read-only)",
    atomicity: str = "not applicable",
    user_content: str = "no user-authored content is rewritten",
    recovery: str = "re-run is safe after operator inspection",
    test_refs: list[str] | None = None,
) -> dict[str, object]:
    return {
        "status": "documented",
        "class": family,
        "writes": writes,
        "locks": locks or [],
        "git_effects": git_effects or [],
        "authority": authority,
        "rollback": rollback,
        "atomicity": atomicity,
        "user_content": user_content,
        "recovery": recovery,
        "source_refs": source_refs,
        "test_refs": test_refs or [],
    }


