#!/usr/bin/env python3
"""Generate CPython 3.11.15/UCD14 decimal facts; development-only, no runtime Python."""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

OUTPUT = Path("crates/sk-kernel/src/python_decimal_data.rs")
SCRIPT = r"""
import json,os,sys,unicodedata
from pathlib import Path
root=Path(os.environ['SK_DECIMAL_ROOT'])
assert Path.cwd()==root and sys.version_info[:3]==(3,11,15)
assert sys.implementation.name=='cpython' and unicodedata.unidata_version=='14.0.0'
for key,name in [
    ('HOME','home'),('XDG_CONFIG_HOME','config'),('XDG_CACHE_HOME','cache'),
    ('XDG_DATA_HOME','data'),('XDG_STATE_HOME','state'),('XDG_RUNTIME_DIR','runtime'),
    ('TMPDIR','tmp'),('TMP','tmp'),('TEMP','tmp')
]:
    assert Path(os.environ[key])==root/name
ranges=[]
for code in range(0x110000):
    char=chr(code);decimal=char.isdecimal()
    assert decimal==(unicodedata.category(char)=='Nd'),code
    if decimal:
        if ranges and code==ranges[-1][1]+1:ranges[-1][1]=code
        else:ranges.append([code,code])
        assert unicodedata.decimal(char)==(code-ranges[-1][0])%10,code
assert sum(end-start+1 for start,end in ranges)==660
print(json.dumps(ranges))
"""


def collect(root: Path) -> list[list[int]]:
    subprocess.run(
        [sys.executable, str(root / "scripts/rust/verify_oracle.py"), "--root", str(root)],
        check=True,
        capture_output=True,
        text=True,
    )
    sandbox = Path(tempfile.mkdtemp(prefix="sk-decimal-facts-"))
    env = {
        "PATH": os.defpath,
        "PYTHONDONTWRITEBYTECODE": "1",
        "SK_DECIMAL_ROOT": str(sandbox),
        "PYTHONPATH": str(root / "src"),
        "SPEC_KITTY_PACKS_ROOT": str(root / "packs"),
    }
    for key, name in [
        ("HOME", "home"),
        ("XDG_CONFIG_HOME", "config"),
        ("XDG_CACHE_HOME", "cache"),
        ("XDG_DATA_HOME", "data"),
        ("XDG_STATE_HOME", "state"),
        ("XDG_RUNTIME_DIR", "runtime"),
        ("TMPDIR", "tmp"),
        ("TMP", "tmp"),
        ("TEMP", "tmp"),
    ]:
        (sandbox / name).mkdir(exist_ok=True)
        env[key] = str(sandbox / name)
    result = subprocess.run(
        [sys.executable, "-c", SCRIPT],
        check=True,
        capture_output=True,
        text=True,
        cwd=sandbox,
        env=env,
    )
    (sandbox / "source.stdout").write_text(result.stdout)
    (sandbox / "source.stderr").write_text(result.stderr)
    return json.loads(result.stdout)


def render(rows: list[list[int]]) -> str:
    header = (
        "// Generated by scripts/rust/generate_python_decimal.py; CPython3.11.15/UCD14.0.0.\n"
        "// All1114112 code points checked against str.isdecimal and category Nd.\n"
        "// 660 decimal characters; digit value is (code - range_start) % 10, Source-verified.\n"
    )
    body = "".join(f"    (0x{start:04x}, 0x{end:04x}),\n" for start, end in rows)
    return header + "pub(crate) const DECIMAL_RANGES: &[(u32, u32)] = &[\n" + body + "];\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    text = render(collect(root))
    path = root / OUTPUT
    if args.check:
        if not path.is_file() or path.read_text() != text:
            print(f"decimal facts differ: {path}", file=sys.stderr)
            return 1
    elif path.exists():
        if path.read_text() != text:
            print(f"refusing to overwrite different decimal facts: {path}", file=sys.stderr)
            return 1
    else:
        path.write_text(text)
    print(f"verified decimal facts: {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
