#!/usr/bin/env python3
"""Generate the additional CPython3.11.15 Unicode regex literal case classes.

The existing Kernel lowercase facts remain the sole lowercase authority. Regex
IGNORECASE uses their single-character mapping's FIRST unit, then re._casefix's
additional equivalences; it is neither contextual lower() nor full casefold().
This development generator verifies all1114112 lower units against _sre, then
checks every extra class with the actual regex matcher. No runtime Python.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

OUTPUT = Path("crates/sk-kernel/src/python_regex_case_data.rs")
FACTS_SCRIPT = r"""
import _sre,json,os,re,sys,unicodedata
from pathlib import Path
from re._casefix import _EXTRA_CASES
root=Path(os.environ['SK_REGEX_ROOT'])
assert Path.cwd()==root
for key in ('HOME','TMPDIR','XDG_CONFIG_HOME','XDG_CACHE_HOME','XDG_DATA_HOME','XDG_STATE_HOME'):
    assert Path(os.environ[key]).parent==root,(key,os.environ[key])
assert sys.version_info[:3]==(3,11,15),sys.version
assert sys.implementation.name=='cpython'
assert unicodedata.unidata_version=='14.0.0'
for code in range(0x110000):
    assert _sre.unicode_tolower(code)==ord(chr(code).lower()[0]),code
rows=[]
for code,others in sorted(_EXTRA_CASES.items()):
    group={code,*others}
    for other in group:
        assert {other,*_EXTRA_CASES.get(other,())}==group,(code,other)
        assert re.fullmatch(re.escape(chr(code)),chr(other),re.I) is not None,(code,other)
    rows.append([code,min(group)])
print(json.dumps(rows))
"""


def collect(root: Path) -> list[list[int]]:
    subprocess.run(
        [sys.executable, str(root / "scripts/rust/verify_oracle.py"), "--root", str(root)],
        check=True,
        capture_output=True,
        text=True,
    )
    directory = tempfile.mkdtemp(prefix="sk-regex-facts-")
    sandbox = Path(directory)
    env = {"PATH": os.defpath, "PYTHONDONTWRITEBYTECODE": "1", "SK_REGEX_ROOT": directory}
    for key, name in [
        ("HOME", "home"),
        ("TMPDIR", "tmp"),
        ("XDG_CONFIG_HOME", "config"),
        ("XDG_CACHE_HOME", "cache"),
        ("XDG_DATA_HOME", "data"),
        ("XDG_STATE_HOME", "state"),
    ]:
        (sandbox / name).mkdir()
        env[key] = str(sandbox / name)
    result = subprocess.run(
        [sys.executable, "-c", FACTS_SCRIPT],
        check=True,
        capture_output=True,
        text=True,
        cwd=sandbox,
        env=env,
    )
    (sandbox / "source.stdout").write_text(result.stdout)
    (sandbox / "source.stderr").write_text(result.stderr)
    return json.loads(result.stdout)


def render(rows: list[list[int]]) -> str:
    body = "".join(f"    (0x{code:04x}, 0x{key:04x}),\n" for code, key in rows)
    return (
        "// Generated by scripts/rust/generate_regex_case.py; CPython3.11.15/UCD14.0.0.\n"
        "// Additional regex IGNORECASE classes only; lowercase facts are NOT duplicated.\n"
        f"// {len(rows)} class-member keys; generator verifies all1114112 simple-lower units.\n"
        "pub(crate) const EXTRA_CASE_KEYS: &[(u32, u32)] = &[\n" + body + "];\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    text = render(collect(root))
    path = root / OUTPUT
    old = path.read_text() if path.is_file() else None
    if args.check:
        if old != text:
            print(f"generated regex case facts differ: {path}", file=sys.stderr)
            return 1
    elif old != text:
        if old is not None and not args.force:
            print(f"refusing to overwrite different facts without --force: {path}", file=sys.stderr)
            return 1
        path.write_text(text)
    print(f"verified regex case facts: {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
